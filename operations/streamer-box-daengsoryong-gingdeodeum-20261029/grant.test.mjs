const options=()=>({expectedPlanHash:ops.PLAN_HASH,lockDeadline:Date.now()+120000,leaseToken});
async function transaction(db,dryRun=false,overrides={}){
 await db.query('BEGIN');try{const result=await ops.grant(db,{...options(),...overrides});await db.query(dryRun?'ROLLBACK':'COMMIT');return result;}catch(e){await db.query('ROLLBACK');throw e;}
}
async function snapshot(db){const out={};for(const table of ['users','user_second_verifications','inventory_items','cnine_user_inventory','inventory_logs','admin_logs','app_meta'])out[table]=(await db.query('SELECT * FROM '+table+' ORDER BY 1,2')).rows;return out;}

test('Gingdeodeum receives four additional boxes for Daengsoryong exactly once; other accounts, inventory and wallets stay unchanged; replay after opening never restores boxes',async()=>{
 const db=await fixture();try{
  const before=await snapshot(db),dry=await transaction(db,true);assert.equal(dry.verification.totalBoxes,4);assert.deepEqual(await snapshot(db),before);
  const result=await transaction(db),after=await snapshot(db);assert.equal(result.verification.recipientCount,1);
  assert.equal(after.inventory_logs.length,1);assert.equal(after.admin_logs.length,1);assert.equal(after.app_meta.length,1);
  for(const table of ['users','user_second_verifications','inventory_items'])assert.deepEqual(after[table],before[table]);
  const unrelated=r=>r.item_code!==gift.code||[52,4859,99999].includes(Number(r.user_id));assert.deepEqual(after.cnine_user_inventory.filter(unrelated),before.cnine_user_inventory.filter(unrelated));
  for(const a of result.receipt.allocations)assert.equal(a.amount,ops.TARGETS.find(t=>t.userId===a.userId).amount);
  assert.equal(result.receipt.allocations[0].userId,'5877');assert.equal(result.receipt.allocations[0].nickname,'깅더듬');assert.equal(result.receipt.allocations[0].amount,4);
  assert.equal(result.receipt.allocations[0].inputNickname,'댕소룡');
  assert.deepEqual(result.receipt.pending,[]);
  const noWrites={query:(sql,args)=>{assert(/^SELECT/i.test(sql));return db.query(sql,args);}};
  assert.equal((await ops.grant(noWrites,{expectedPlanHash:ops.PLAN_HASH})).replayed,true);assert.deepEqual(await snapshot(db),after);
  await db.query('UPDATE cnine_user_inventory SET quantity=quantity-1 WHERE user_id=$1 AND item_code=$2',[ops.IDS[0],gift.code]);
  const spent=await snapshot(db);assert.equal((await ops.grant(noWrites,{expectedPlanHash:ops.PLAN_HASH})).replayed,true);assert.deepEqual(await snapshot(db),spent);
 }finally{await db.close();}
});

test('late ledger, audit and receipt failures roll back every recipient',async()=>{
 const db=await fixture();try{
  for(const table of ['inventory_logs','admin_logs','app_meta']){
   await db.exec('ALTER TABLE '+table+' ADD CONSTRAINT fail_write CHECK(false)');const before=await snapshot(db);
   await assert.rejects(transaction(db),/fail_write/);assert.deepEqual(await snapshot(db),before);await db.exec('ALTER TABLE '+table+' DROP CONSTRAINT fail_write');
  }
  assert.equal((await transaction(db)).verification.totalBoxes,4);
 }finally{await db.close();}
});

