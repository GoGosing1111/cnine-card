test('late ledger, audit and receipt failures roll back every recipient',async()=>{
 const db=await fixture();try{
  for(const table of ['inventory_logs','admin_logs','app_meta']){
   await db.exec('ALTER TABLE '+table+' ADD CONSTRAINT fail_write CHECK(false)');const before=await snapshot(db);
   await assert.rejects(transaction(db),/fail_write/);assert.deepEqual(await snapshot(db),before);await db.exec('ALTER TABLE '+table+' DROP CONSTRAINT fail_write');
  }
  assert.equal((await transaction(db)).verification.totalBoxes,390);
 }finally{await db.close();}
});

