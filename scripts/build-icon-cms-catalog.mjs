import fs from 'node:fs/promises';
import {ICON_CARD_ROSTER} from '../shared/icon-card-roster-v1.mjs';
const root=new URL('../',import.meta.url), manifest=JSON.parse(await fs.readFile(new URL('preview/icon-battle-assets-v1/manifest.json',root)));
const cards=ICON_CARD_ROSTER.map(photo=>{
  const sd=manifest.characters.find(c=>c.code===photo.code);
  if(!sd)throw Error(`Missing SD: ${photo.code}`);
  const effects=[sd.hitEffect,sd.skillEffect].map(id=>{
    const effect=manifest.effects.find(e=>e.id===id);
    if(!effect)throw Error(`Missing effect: ${id}`);
    return {id,name:effect.name,kind:effect.kind,frameCount:effect.frameCount,duration:effect.duration,contactAt:effect.contactAt};
  });
  return {...photo,id:sd.id,weapon:sd.weapon,accent:sd.accent,battleSprite:'preview/icon-battle-assets-v1/'+sd.runtime,visualApproval:sd.visualApproval,effects};
});
await fs.writeFile(new URL('shared/icon-cms-catalog-v1.mjs',root),'// Generated by scripts/build-icon-cms-catalog.mjs. CMS only; never a playable card registry.\nexport const ICON_CMS_CATALOG='+JSON.stringify(cards,null,2)+';\n');
console.log(`ICON CMS catalog: ${cards.length} portraits + SD, ${cards.reduce((n,c)=>n+c.effects.length,0)} character effects; public release OFF.`);
