// Rebuild measured charts from a read-only export of the existing auction rules.
// node scripts/build-nox-charts.mjs <catalog.json> <analysis-output.json>
import fs from 'node:fs';
import path from 'node:path';
import {createHash} from 'node:crypto';
import {execFileSync} from 'node:child_process';
import http from 'node:http';
import {pathToFileURL} from 'node:url';
import {buildNoxBeatGrid,buildNoxChart} from './lib/nox-chart-authoring.mjs';
const {chromium}=await import(process.env.PLAYWRIGHT_MODULE||'file:///C:/Users/User/.cache/codex-runtimes/codex-primary-runtime/dependencies/node/node_modules/playwright/index.mjs');
const [catalogFile,reportFile]=process.argv.slice(2);
if(!catalogFile||!reportFile)throw Error('Pass the auction catalog export and analysis output paths.');
const catalog=JSON.parse(fs.readFileSync(catalogFile,'utf8'));
const rules=(catalog.bgm||catalog).filter(r=>/\.mp3(?:#|$)/i.test(r.bgm_url));
const files=new Map();
for(const r of rules){const source='/'+r.bgm_url.replace(/^\//,'').replace(/#av=\d+$/,'');if(files.has(source))continue;const name=decodeURIComponent(source.slice(1));if(!name.startsWith('assets/effects/')||name.includes('..'))throw Error('Unexpected catalog path');const bytes=fs.existsSync(name)?fs.readFileSync(name):execFileSync('git',['show','HEAD:'+name],{maxBuffer:30e6,windowsHide:true});files.set(source,{bytes,order:Number(r.sort_order)+1});}
const server=http.createServer((req,res)=>{const f=files.get(req.url);res.setHeader('content-type',f?'audio/mpeg':'text/html');res.end(f?f.bytes:'<!doctype html><title>Local audio analysis</title>');});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const browser=await chromium.launch({headless:true,executablePath:process.env.CHROMIUM_EXECUTABLE||'C:/Program Files/Google/Chrome/Application/chrome.exe'});
const tracks=[],skipped=[],analysis=[],beatGrids={};
try{
 const page=await browser.newPage();await page.goto('http://127.0.0.1:'+server.address().port);
 for(const [source,{bytes,order}] of files){
  const measured=await page.evaluate(async source=>{
   const context=new OfflineAudioContext(1,1,22050),buffer=await context.decodeAudioData(await (await fetch(source)).arrayBuffer()),hop=220,energies=[],kickEnergies=[];
   // Mix channels: a hard-panned kick must not vanish from the chart.
   const channels=Array.from({length:buffer.numberOfChannels},(_,i)=>buffer.getChannelData(i));
   const lowPass=1-Math.exp(-2*Math.PI*140/buffer.sampleRate);
   const low=channels.map(()=>0);
   for(let i=0;i+hop<buffer.length;i+=hop){
    let sum=0,kick=0;
    for(let j=0;j<hop;j++){
     let x=0;
     for(let channel=0;channel<channels.length;channel++){
      const sample=channels[channel][i+j];
      x+=sample/channels.length;
      low[channel]+=lowPass*(sample-low[channel]);
      kick+=low[channel]**2/channels.length;
     }
     sum+=x*x;
    }
    energies.push(Math.sqrt(sum/hop));
    kickEnergies.push(Math.sqrt(kick/hop));
   }
   return {energies,kickEnergies,durationMs:Math.round(buffer.duration*1000),rate:buffer.sampleRate,hop};
  },source);
  const {durationMs}=measured,authored=buildNoxChart(measured.energies,measured);
  if(durationMs<31000||!authored){skipped.push({source,durationMs,reason:'insufficient measured rhythm segment'});continue;}
  const sha256=createHash('sha256').update(bytes).digest('hex');
  const id='bgm-'+sha256.slice(0,12)+'-full1';
  const beatGrid=buildNoxBeatGrid(measured.kickEnergies,measured);
  if(beatGrid)beatGrids[id]=beatGrid;
  const {notes,...details}=authored;analysis.push({source,durationMs,...details,beatGrid});
  tracks.push({id,name:'경매 BGM '+String(order).padStart(2,'0'),source,sha256,durationMs,chartStartMs:5000,chartEndMs:durationMs,notes});
 }
}finally{await browser.close();await new Promise(r=>server.close(r));}
if(tracks.length<3)throw Error('At least three measured songs required');
const method='Full MP3: 22.05 kHz mixed mono RMS onset anchors; 10ms hop, 150ms minimum onset spacing; measured-pulse rest/fade continuation, 27% two-key accents, same-lane separation >=330ms. Optional beat grid from phase concentration of 140Hz low-pass RMS rises across channels.';
const previous=await import(pathToFileURL(path.resolve('shared/nox-raid-chart-v1.mjs'))),legacy=previous.NOX_TRACK,legacyTracks=previous.NOX_LEGACY_TRACKS||previous.NOX_TRACKS;
// Versioned IDs retain exact legacy charts for rooms already created/deployed.
const data='// Generated by scripts/build-nox-charts.mjs; full-song revision 2026-11-20.\n'+
 'export const NOX_TRACK = Object.freeze('+JSON.stringify(legacy)+');\n'+
 'export const NOX_LEGACY_TRACKS = Object.freeze([\n'+legacyTracks.map(t=>'  Object.freeze('+JSON.stringify(t)+')').join(',\n')+'\n]);\n'+
 'export const NOX_TRACKS = Object.freeze([\n'+tracks.map(t=>'  Object.freeze('+JSON.stringify(t)+')').join(',\n')+'\n]);\n'+
 'export const NOX_BEAT_GRIDS = Object.freeze({\n'+Object.entries(beatGrids).map(([id,grid])=>'  '+JSON.stringify(id)+': Object.freeze('+JSON.stringify(grid)+')').join(',\n')+'\n});\n'+
 `export const NOX_CLIENT_VERSION = 6;
export const NOX_RHYTHM_VERSION = 2;
export const NOX_RHYTHM_RULES = Object.freeze({perfectMs:80,goodMs:160,goodScore:.95,maxMiss:3,accuracy:.9,travelMs:1250,holdReleaseMs:75,holdMaxMs:1100});
const trackById=new Map([...NOX_LEGACY_TRACKS,...NOX_TRACKS].map(t=>[t.id,t]));
export function noxTrack(id){return trackById.get(id)||NOX_TRACK;}
export function noxPlaylist(seed){
  let value=(seed^0x9e3779b9)>>>0;const tracks=NOX_TRACKS.map(t=>t.id);
  for(let i=tracks.length-1;i>0;i--){value=(Math.imul(value,1664525)+1013904223)>>>0;const j=Math.floor(value/4294967296*(i+1));[tracks[i],tracks[j]]=[tracks[j],tracks[i]];}
  return tracks.slice(0,3);
}
export function judgeNoxNote(notes,hits,lane,at,windowMs=NOX_RHYTHM_RULES.goodMs){
  let best=null,delta=Infinity;
  for(const note of notes){if(note.lane!==lane||hits.has(note.id))continue;const d=Math.abs(note.at-at);if(d<=windowMs&&d<delta){best=note;delta=d;}}
  return best?{note:best,delta,grade:delta<=NOX_RHYTHM_RULES.perfectMs?'PERFECT':'GOOD'}:null;
}
`;
fs.writeFileSync('shared/nox-raid-chart-v1.mjs',data);
fs.mkdirSync(path.dirname(reportFile),{recursive:true});fs.writeFileSync(reportFile,JSON.stringify({method,tracks,analysis,skipped},null,2)+'\n');
console.log(JSON.stringify({tracks:tracks.length,notes:tracks.map(t=>({name:t.name,count:t.notes.length})),skipped,bytes:Buffer.byteLength(data)}));
