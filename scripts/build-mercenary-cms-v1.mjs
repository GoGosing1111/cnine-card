import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {MERCENARY_SKILLS} from '../shared/mercenary-skills-v1.mjs';
import {POSITIONS, ROLES, TARGETS} from '../shared/mercenary-position-config-v1.mjs';
import {MERCENARY_RANKS} from '../shared/mercenary-ranks-v1.mjs';
const read = path => JSON.parse(readFileSync(new URL('../'+path, import.meta.url), 'utf8'));
const roster = read('assets/ui/project-v/mercenaries/mercenary-system-roster-v1.json');
const positions = read('preview/project-v-mercenary-system-v1/position-draft-v1.json');
const fx = read('preview/project-v-mercenary-system-v1/skill-assets-v2/manifest.json');
const catalog = {version:1, rosterVersion:roster.version, ranks:MERCENARY_RANKS,
  positions:POSITIONS, roles:ROLES, targets:TARGETS, formation:roster.formationRule,
  cards:roster.cards, skills:MERCENARY_SKILLS, effects:fx,
  release:{group:'V3_MERCENARY_EQUIPMENT',acquisitionEnabled:false,formationEnabled:false,battleEnabled:false}};
const document = {format:'MERCENARY_CMS_V1',rosterVersion:roster.version,status:'DRAFT',runtimeEnabled:false,
  mercenaries:roster.cards.map(card => ({...positions.assignments.find(row=>row.code===card.code),
    name:card.name,title:card.title,stats:{hp:null,attack:null,defense:null,speed:null},
    acquisition:{type:'UNSET',source:'',coinPrice:null,dropRate:null},
    growth:{maxLevel:null,hpPerLevel:null,attackPerLevel:null,defensePerLevel:null},
    review:'PENDING',notes:''})),
  skills:MERCENARY_SKILLS.map(skill=>({id:skill.id,name:skill.name,role:skill.role,target:skill.target,
    mechanic:skill.mechanic,trigger:skill.trigger,effect:skill.effect,counterplay:skill.counterplay,
    bossRule:skill.bossRule,procRule:skill.procRule,
    balance:{damageRatio:null,cooldownTurns:null,cost:null},review:'PENDING',notes:''})),
  assignments:roster.cards.map(card=>({code:card.code,skillIds:[]})),
  settings:{rankGrowth:MERCENARY_RANKS.map(rank=>({rank,maxLevel:null,coinPerLevel:null,expPerLevel:null})),
    acquisitionNotes:'',growthNotes:'',releaseNotes:'V3 개편·용병·장비 강화 공동 출시. CMS 저장은 게임 활성화가 아닙니다.'}};
const sourceHash = createHash('sha256').update(JSON.stringify({catalog,document})).digest('hex');
writeFileSync(new URL('../functions/_mercenary_cms_seed.js',import.meta.url),
  '// Generated by scripts/build-mercenary-cms-v1.mjs. Canonical art and SD are immutable.\n'+
  `export const MERCENARY_CMS_SEED = ${JSON.stringify({sourceHash,catalog,document})};\n`);
console.log(`CMS seed: ${catalog.cards.length} mercenaries / ${catalog.skills.length} skills / ${sourceHash}`);
