// Invoke in an isolated review-page browser context. Restores browser draft storage.
export async function runMercenaryPositionBrowserQa() {
  if (!location.pathname.endsWith('/preview/project-v-mercenary-system-v1/positions.html')) throw new Error('Position preparation page only');
  const model = await import('/shared/mercenary-position-config-v1.mjs');
  const $ = selector => document.querySelector(selector);
  const seed = await (await fetch('./position-draft-v1.json')).json();
  const storageBefore = localStorage.getItem(model.DRAFT_STORAGE_KEY);
  const originalConfirm = window.confirm;
  const originalCreateUrl = URL.createObjectURL;
  const originalClick = HTMLAnchorElement.prototype.click;
  const checks = [];
  const check = (name, ok) => { checks.push({ name, ok: Boolean(ok) }); if (!ok) throw new Error(name); };
  const pause = () => new Promise(resolve => setTimeout(resolve, 60));
  const input = (selector, value, type = 'input') => { const el = $(selector); el.value = value; el.dispatchEvent(new Event(type, { bubbles: true })); };
  const importFile = async content => {
    const transfer = new DataTransfer();
    transfer.items.add(new File([content], 'draft.json', { type: 'application/json' }));
    $('#importDraft').files = transfer.files;
    $('#importDraft').dispatchEvent(new Event('change', { bubbles: true }));
    await pause();
  };
  let exported;
  try {
    window.confirm = () => true;
    localStorage.setItem(model.DRAFT_STORAGE_KEY, JSON.stringify(seed));
    $('#reloadDraft').click();
    $('#clearFilters').click();
    check('43 mercenaries present', document.querySelectorAll('.roster-row').length === 43);
    check('7 distinct role selectors', document.querySelectorAll('.role-card').length === 7);
    check('initial position counts 20/15/8', [...document.querySelectorAll('.position-item strong')].map(el => el.textContent).join('/') === '20/15/8');
    const images = [...document.querySelectorAll('.portrait')];
    await Promise.all(images.map(async img => { img.loading = 'eager'; await img.decode(); }));
    check('all 43 original-art thumbnails load', images.every(img => img.naturalWidth === 320 && img.src.includes('-art-320.webp')));
    input('#search', '경찰 조은');
    check('name search finds Joeun only', document.querySelectorAll('.roster-row').length === 1 && $('.roster-row').dataset.code === 'V-042');
    $('.roster-row').click();
    check('Joeun opens with proposed controller role', $('#editRole').value === 'CONTROLLER');
    $('#clearFilters').click();
    $('.role-card[data-role="SUPPORT"]').click();
    check('support role filter finds three candidates', document.querySelectorAll('.roster-row').length === 3);
    input('#positionFilter', 'FRONT');
    check('combined filter selects Yeonhwi', document.querySelectorAll('.roster-row').length === 1 && $('.roster-row').dataset.code === 'V-028');
    input('#search', '없는용병');
    check('empty filter result is explained', document.querySelectorAll('.roster-row').length === 0 && $('#rosterList').textContent.includes('없습니다'));
    $('#clearFilters').click();
    $('.roster-row[data-code="V-003"]').click();
    input('#editRole', 'SNIPER', 'change');
    check('role edit selects a compatible position and target', $('#editPosition').value === 'REAR' && $('#editTarget').value === 'BACK_THREAT');
    check('keyboard focus survives dependent select update', document.activeElement.id === 'editRole');
    input('#editSpecialty', '검수용 <b>정밀 사격</b>');
    $('#saveDraft').click();
    const saved = JSON.parse(localStorage.getItem(model.DRAFT_STORAGE_KEY));
    check('local save increments revision with no activation', saved.revision === 2 && saved.runtimeEnabled === false && saved.status === 'DRAFT');
    check('saved draft contains reviewed role assignment', saved.assignments.find(entry => entry.code === 'V-003').role === 'SNIPER');
    $('#reloadDraft').click();
    check('saved value reloads as literal text', $('#editSpecialty').value === '검수용 <b>정밀 사격</b>' && !$('#editSpecialty b'));
    URL.createObjectURL = blob => { exported = blob; return originalCreateUrl(blob); };
    HTMLAnchorElement.prototype.click = function () { if (!this.download.startsWith('mercenary-position-draft-')) originalClick.call(this); };
    $('#exportDraft').click();
    const exportedJson = JSON.parse(await exported.text());
    check('JSON export preserves all assignments and draft status', exportedJson.assignments.length === 43 && exportedJson.status === 'DRAFT');
    const invalid = { ...exportedJson, runtimeEnabled: true };
    await importFile(JSON.stringify(invalid));
    check('runtime activation import is rejected', $('#notice').classList.contains('error') && $('#notice').textContent.includes('가져오기 실패'));
    check('failed import preserves saved revision and edited assignment', localStorage.getItem(model.DRAFT_STORAGE_KEY) === JSON.stringify(saved) && $('#editRole').value === 'SNIPER');
    await importFile('{');
    check('malformed JSON import is rejected', $('#notice').textContent.includes('가져오기 실패'));
    await importFile(JSON.stringify(seed));
    check('valid import changes draft without overwriting saved revision', $('#editRole').value === 'GUARDIAN' && JSON.parse(localStorage.getItem(model.DRAFT_STORAGE_KEY)).revision === 2);
    const newer = { ...saved, revision: 3 };
    localStorage.setItem(model.DRAFT_STORAGE_KEY, JSON.stringify(newer));
    $('#saveDraft').click();
    check('stale editor refuses overwrite', $('#notice').textContent.includes('다른 편집') && JSON.parse(localStorage.getItem(model.DRAFT_STORAGE_KEY)).revision === 3);
    $('#reloadDraft').click();
    check('fresh reload recovers after conflict', $('#draftState').textContent.includes('수정 번호 3') && $('#editRole').value === 'SNIPER');
    $('#restoreEntry').click();
    check('per-card default restoration affects working draft only', $('#editRole').value === 'GUARDIAN' && JSON.parse(localStorage.getItem(model.DRAFT_STORAGE_KEY)).assignments[2].role === 'SNIPER');
    input('#editWeakness', ' ');
    $('#saveDraft').click();
    check('empty weakness cannot be saved', $('#notice').classList.contains('error') && JSON.parse(localStorage.getItem(model.DRAFT_STORAGE_KEY)).revision === 3);
    check('no horizontal page overflow', document.documentElement.scrollWidth <= innerWidth);
    check('form controls have touch-sized targets', ['#editRole', '#editPosition', '#saveDraft', '#exportDraft'].every(selector => $(selector).getBoundingClientRect().height >= 44));
    check('no account or admin API request', !performance.getEntriesByType('resource').some(entry => new URL(entry.name).pathname.startsWith('/api/')));
    return { ok: true, viewport: `${innerWidth}x${innerHeight}`, assertions: checks.length, checks };
  } finally {
    if (storageBefore === null) localStorage.removeItem(model.DRAFT_STORAGE_KEY); else localStorage.setItem(model.DRAFT_STORAGE_KEY, storageBefore);
    $('#reloadDraft').click();
    $('#clearFilters').click();
    $('.roster-row[data-code="V-001"]').click();
    window.confirm = originalConfirm;
    URL.createObjectURL = originalCreateUrl;
    HTMLAnchorElement.prototype.click = originalClick;
    window.scrollTo(0, 0);
  }
}
