import fs from 'node:fs/promises';
import path from 'node:path';
import {execFileSync} from 'node:child_process';
import {createHash} from 'node:crypto';
import sharp from 'sharp';
import {limitedDeploymentSnapshot} from '../shared/mercenary-limited-deployment-v1.mjs';

// Deterministic delivery derivatives. Approved originals are read, never changed.
const root=path.resolve(import.meta.dirname,'..'),revision=process.env.BATTLE_IMAGE_SOURCE_REF||'HEAD';
const git=(...args)=>execFileSync('git',['-c','gc.auto=0',...args],{cwd:root,windowsHide:true,maxBuffer:80e6});
const files=git('ls-tree','-r','--name-only',revision,'assets/ui/project-v/mercenaries').toString().trim().split(/\r?\n/);
async function read(file){try{return await fs.readFile(path.join(root,file));}catch{return git('show',revision+':'+file);}}
const inputs=new Map();
for(let n=1;n<1000;n++){
 const card=limitedDeploymentSnapshot('V-'+String(n).padStart(3,'0'));
 if(card?.sourceArt)inputs.set(card.sourceArt.replace(/^\//,''),'portrait');
}
for(const file of files.filter(p=>/\.atlas$/.test(p)&&/\/(?:jin-jokro-20261106|helios-king-20261106|hakuya-shin-20261105|blue-gear-live-v1)\//.test(p))){
 const content=(await read(file)).toString();
 for(const page of content.split(/\r?\n/).filter(line=>/\.(?:png|webp)$/.test(line.trim())))inputs.set(path.posix.join(path.posix.dirname(file),page.trim()),'spine');
}
for(const file of ['assets/ui/coin-prediction/arena-v1.png','assets/ui/project-v/battlefields/v3-nightmare-forest-battlefield-v1.png','assets/ui/project-v/battlefields/v3-world-raid-obsidian-citadel-v1.png','assets/ui/project-v/battlefields/v3-siege-fortress-courtyard-v1.png','assets/ui/cooperative-arke-v1/forge-arena-v1.png'])inputs.set(file,'background');
// Authored motion/FX pages observed in ranked, duo, Legion and co-op profiles.
{
 const report=JSON.parse(await fs.readFile(process.env.BATTLE_IMAGE_PROFILE||path.join(root,'docs/qa/iphone-combat-20261114/profile.json'),'utf8'));
 for(const row of report.rows||[])for(const image of row.images||[]){
  const file=new URL(image.url,'https://local.invalid').pathname.slice(1);
  if(!image.url.includes('#')&&/\.(?:png|webp|jpe?g)$/.test(file)&&image.bytes>3*1048576&&/^(?:assets\/|preview\/(?:mercenary-|prime-requiem-|sustained-hunt-|battle-suit-))/.test(file))if(!inputs.has(file))inputs.set(file,'motion');
 }
}
const directory='assets/optimized/iphone-battle-20261114',rows=[],map={};
await fs.mkdir(path.join(root,directory),{recursive:true});
for(const [file,kind]of [...inputs].sort(([a],[b])=>a.localeCompare(b))){
 const original=await read(file),meta=await sharp(original).metadata();let scale=1;
 const max=kind==='portrait'?512:1024;
 while(Math.max(meta.width,meta.height)*scale>max)scale/=2;
 // Do not add copies of already small, efficient WebPs.
 if(scale===1&&original.length<150000)continue;
 const width=Math.round(meta.width*scale),height=Math.round(meta.height*scale);
 const bytes=await sharp(original).resize(width,height,{kernel:'lanczos3',fit:'fill'}).webp({quality:86,alphaQuality:100,effort:5}).toBuffer();
 if(scale===1&&bytes.length>=original.length*.85)continue;
 const sha256=createHash('sha256').update(original).digest('hex'),output=directory+'/'+createHash('sha256').update(bytes).digest('hex').slice(0,20)+'.webp';
 await fs.writeFile(path.join(root,output),bytes);
 map['/'+file]=['/'+output,scale,meta.width,meta.height];
 rows.push({source:file,kind,sourceSha256:sha256,width:meta.width,height:meta.height,scale,sourceBytes:original.length,output,bytes:bytes.length,rgbaBefore:meta.width*meta.height*4,rgbaAfter:width*height*4});
}
await fs.writeFile(path.join(root,'preview/project-v-v3/source/battle/BattleMobileImages.mjs'),'// Generated by scripts/build-iphone-battle-images.mjs; original geometry is preserved.\nexport const BATTLE_MOBILE_IMAGES=Object.freeze('+JSON.stringify(map,null,2)+');\n');
await fs.mkdir(path.join(root,'docs/qa/iphone-combat-20261114'),{recursive:true});
const sum=key=>rows.reduce((n,r)=>n+r[key],0);
const report={version:'20261114-v1',rows,totals:{files:rows.length,sourceBytes:sum('sourceBytes'),bytes:sum('bytes'),rgbaBefore:sum('rgbaBefore'),rgbaAfter:sum('rgbaAfter')}};
await fs.writeFile(path.join(root,'docs/qa/iphone-combat-20261114/images.json'),JSON.stringify(report,null,2)+'\n');
console.log(JSON.stringify(report.totals));
