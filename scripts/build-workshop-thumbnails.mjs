// Presentation derivatives only. Preserve every source image byte-for-byte.
import fs from 'node:fs/promises';
import path from 'node:path';
import vm from 'node:vm';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import sharp from 'sharp';

const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const sources=JSON.parse(await fs.readFile(path.join(root,'assets/ui/workshop/thumbnail-sources-v1.json'),'utf8'));
const output='assets/ui/workshop/thumbnails';
await fs.mkdir(path.join(root,output),{recursive:true});
const context={window:{}};
vm.runInNewContext(await fs.readFile(path.join(root,'js/equipment-thumbnails-v1.js'),'utf8'),context);
// Reuse the already shipped equipment derivatives, without rebuilding their art.
const map={...context.window.SoopketmonEquipmentThumbnails},stats=[];
for(const {source,size} of sources){
  const absolute=path.resolve(root,source);
  if(!absolute.startsWith(root+path.sep)||![128,384,768].includes(size))throw Error('Invalid workshop thumbnail source');
  const original=await fs.readFile(absolute);
  const hash=createHash('sha256').update(original).digest('hex').slice(0,16);
  const target=`${output}/${hash}-${size}.webp`;
  const result=await sharp(original).rotate().resize(size,size,{fit:'inside',withoutEnlargement:true}).webp({quality:84,effort:5}).toBuffer();
  await fs.writeFile(path.join(root,target),result);
  map[source]=target;stats.push({source,original:original.length,thumbnail:result.length});
}
await fs.writeFile(path.join(root,'js/workshop-thumbnails-v1.js'),'// Generated by scripts/build-workshop-thumbnails.mjs. Original art is unchanged.\nwindow.SoopketmonWorkshopThumbnails=Object.freeze('+JSON.stringify(map)+');\n');
console.log(JSON.stringify({items:stats.length,sourceBytes:stats.reduce((n,r)=>n+r.original,0),thumbnailBytes:stats.reduce((n,r)=>n+r.thumbnail,0),stats}));
