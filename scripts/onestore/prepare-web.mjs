import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {join,dirname,resolve} from 'node:path';
import {fileURLToPath} from 'node:url';
import {build} from 'esbuild';
import {createWebOverrides} from './web-overrides.mjs';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'../..');
const verify=process.argv.includes('--check');
const {overrides,hashes,source,once,hash}=await createWebOverrides(root);
// Only a dozen client variants, not a project/assets/dependencies copy.
for(const file of ['js/adventure-navigation-standalone.js','pet-codex/app.mjs','js/pet-deck-slot-v1.mjs','js/pet-opening-v1.mjs'])overrides.set('/'+file,await source(file));
overrides.delete('/js/store-distribution-v1.js'); // the early H5 policy includes it
let adapter=overrides.get('/js/soopketmon-v21-exact-shell-adapter.js');
adapter=once(adapter,"new URL(`../css/${filename}`, script.src).href","new URL(`/css/${filename}`, location.origin).href",'canonical styles');
adapter=once(adapter,"      try { if (global.top && global.top !== global) global.top.location.href = 'https://cnine-card.pages.dev/'; } catch (_error) { global.open('https://cnine-card.pages.dev/', '_blank', 'noopener,noreferrer'); }","      // Fullscreen is optional in the ONE store parent iframe.",'no frame escape');
overrides.set('/js/soopketmon-v21-exact-shell-adapter.js',adapter);
const navigation=overrides.get('/js/adventure-navigation-standalone.js');
overrides.set('/js/adventure-navigation-standalone.js',once(navigation,"location.assign(href||'/?screen='+encodeURIComponent(id))","location.assign(window.CNineStoreWeb.storeDocumentUrl(href||'/?screen='+encodeURIComponent(window.CNineStorePolicy.routeFor(id)),location.href)||'/onestore/')",'standalone route retention'));
const paths=[...overrides.keys()].sort();
const mapReferences=(text,file)=>{
  // Absolute source references inside both static tags and dynamic imports.
  for(const path of [...paths].sort((a,b)=>b.length-a.length))text=text.replaceAll(path,'/onestore'+path);
  // Resolve relative module imports at their original URL, preserving queries.
  if(/\.m?js$/.test(file))text=text.replace(/(['"])(\.{1,2}\/[^'"\s]+)\1/g,(all,quote,value)=>{
    const url=new URL(value,'https://cnine-card.pages.dev'+file);
    return quote+(paths.includes(url.pathname)?'/onestore':'')+url.pathname+url.search+url.hash+quote;
  });
  return text;
};
const outputs=new Map();
for(const [path,value]of overrides){
  if(path==='/index.html')continue;
  outputs.set('onestore'+path,mapReferences(value,path));
}
for(const name of ['h5-policy','h5-sdk']){
  const result=await build({entryPoints:[join(root,'packaging/onestore/web',name+'.mjs')],bundle:true,write:false,format:name==='h5-sdk'?'esm':'iife',target:'es2020',minify:true,external:['https://*'],metafile:true});
  outputs.set('onestore/'+name+'.js',result.outputFiles[0].text);
  for(const file of Object.keys(result.metafile.inputs))await source(file.replaceAll('\\','/'));
}
outputs.set('onestore/h5.css',await source('packaging/onestore/web/h5.css'));
const assetVersions=Object.fromEntries([...outputs].map(([p,v])=>['/'+p,hash(v).slice(0,12)]));
// The server transforms standalone documents from their live canonical source.
// The main entry also has structural exclusions from the reviewed APK variant.
outputs.set('onestore/index.html',overrides.get('/index.html'));
outputs.set('shared/onestore-web-assets-v1.mjs','// Generated by scripts/onestore/prepare-web.mjs\nexport const variantPaths='+JSON.stringify(paths.filter(p=>p!=='/index.html'))+';\nexport const assetVersions='+JSON.stringify(assetVersions)+';\n');
for(const [file,value]of outputs){
  const path=join(root,file);
  if(verify){if(await readFile(path,'utf8')!==value)throw Error('Stale ONE store web variant: '+file);}
  else{await mkdir(dirname(path),{recursive:true});await writeFile(path,value);}
}
const manifest=JSON.stringify({sourceHashes:hashes,outputs:Object.fromEntries([...outputs].map(([p,v])=>[p,hash(v)]))},null,2)+'\n';
if(verify){if(await readFile(join(root,'packaging/onestore/web-build.json'),'utf8')!==manifest)throw Error('Stale ONE store source manifest');}
else await writeFile(join(root,'packaging/onestore/web-build.json'),manifest);
console.log(JSON.stringify({verified:verify,files:outputs.size,bytes:[...outputs.values()].reduce((n,v)=>n+Buffer.byteLength(v),0)}));
