import { createHash } from 'node:crypto';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import sharp from 'sharp';
import { MERCENARY_CMS_SEED } from '../functions/_mercenary_cms_seed.js';
import { mercenaryCodexDocument } from '../functions/_mercenary_codex.js';

const root = new URL('../', import.meta.url);
const folder = 'assets/ui/legion-citadel/portraits-v1/';
const catalog = mercenaryCodexDocument({ payload_json: JSON.stringify(MERCENARY_CMS_SEED.document), revision: 1 });
const cards = catalog.cards.toSorted((a, b) => a.code.localeCompare(b.code));
const sources = [...new Set(cards.map(card => card.sourceArt))];
const columns = 4;
const perSheet = columns * columns;
const width = 105, height = 132; // Three physical pixels per CSS pixel in the picker.
const sheets = [];
await mkdir(new URL(folder, root), { recursive: true });

for (let start = 0; start < sources.length; start += perSheet) {
  const group = sources.slice(start, start + perSheet);
  const tiles = [];
  for (const [index, source] of group.entries()) {
    const { data, info } = await sharp(fileURLToPath(new URL(source, root))).autoOrient()
      .resize(width, height, { fit: 'outside' }).png().toBuffer({ resolveWithObject: true });
    // Match the original portrait's object-fit: cover and object-position: center 22%.
    const tile = await sharp(data).extract({ width, height,
      left: Math.round((info.width - width) / 2), top: Math.round((info.height - height) * 0.22)
    }).png().toBuffer();
    tiles.push({ input: tile, left: (index % columns) * width, top: Math.floor(index / columns) * height });
  }
  const sheet = await sharp({ create: {
    width: columns * width, height: columns * height, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 }
  } }).composite(tiles).webp({ quality: 80, effort: 6 }).toBuffer();
  const hash = createHash('sha256').update(sheet).digest('hex').slice(0, 16);
  const file = folder + hash + '.webp';
  await writeFile(new URL(file, root), sheet);
  sheets.push({ image: '/' + file, sources: group.map(source => '/' + source) });
}
const generated = '// Generated by scripts/build-legion-party-portraits.mjs\n'
  + 'export const portraitSheets = ' + JSON.stringify(sheets, null, 2) + ';\n';
await writeFile(new URL('js/legion-party-portrait-sheets-v1.mjs', root), generated);
console.log('Packed ' + sources.length + ' party portraits into ' + sheets.length + ' WebP sheets.');
