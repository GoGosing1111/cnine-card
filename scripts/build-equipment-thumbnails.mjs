import fs from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {createHash} from 'node:crypto';
import sharp from 'sharp';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const sources=JSON.parse(await fs.readFile(path.join(root,'assets/ui/character-loadout-v2/equipment-thumbnail-sources.json'),'utf8'));
const output='assets/ui/character-loadout-v2/thumbnails';await fs.mkdir(path.join(root,output),{recursive:true});
const map={},stats=[];
for(const source of sources){
  const absolute=path.resolve(root,source);
  if(!absolute.startsWith(root+path.sep))throw Error('Image must be inside the repository');
  const original=await fs.readFile(absolute),hash=createHash('sha256').update(original).digest('hex').slice(0,16);
  const target=`${output}/${hash}-384.webp`;
  const result=await sharp(original).rotate().resize(384,384,{fit:'inside',withoutEnlargement:true}).webp({quality:84,effort:5}).toBuffer();
  await fs.writeFile(path.join(root,target),result);map[source]=target;stats.push({source,original:original.length,thumbnail:result.length});
}
await fs.writeFile(path.join(root,'js/equipment-thumbnails-v1.js'),'// Generated by scripts/build-equipment-thumbnails.mjs. Original art is unchanged.\nwindow.SoopketmonEquipmentThumbnails=Object.freeze('+JSON.stringify(map)+');\n');
const bannerSource='preview/equipment-forge-v1/assets/upgrade-lab-v2.png';
const banner=await fs.readFile(path.join(root,bannerSource));
const bannerResult=await sharp(banner).resize({width:1280,withoutEnlargement:true}).webp({quality:80,effort:5}).toBuffer();
await fs.writeFile(path.join(root,'assets/ui/character-loadout-v2/forge-entry-1280.webp'),bannerResult);
console.log(JSON.stringify({items:stats.length,sourceBytes:stats.reduce((n,r)=>n+r.original,0),thumbnailBytes:stats.reduce((n,r)=>n+r.thumbnail,0),bannerSourceBytes:banner.length,bannerBytes:bannerResult.length}));
