  const result=await syncBlueBeastTitle(f.env,7);assert.equal(result.granted.length,1);assert.equal(result.progress.BLUE_BEAST.owned,10);
  assert.deepEqual(await syncBlueBeastTitle(f.env,7),{granted:[],progress:{}});
  assert.equal((await syncBlueBeastTitle(f.env,8)).granted.length,0);
  const owned=(await f.p('SELECT u.*,t.code FROM user_character_titles u JOIN character_titles t ON t.id=u.title_id').all()).results;
  assert.equal(owned.length,1);assert.equal(owned[0].code,'BLUE_BEAST');assert.equal(owned[0].source_type,'ACHIEVEMENT');assert.equal(Number(owned[0].user_id),7);
