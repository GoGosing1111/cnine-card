  await f.p("INSERT INTO pvp_season_settlements VALUES(21,'PROCESSING','2026-09-01'),(22,'COMPLETED',NULL),(23,'COMPLETED','2026-09-01'),(24,'COMPLETED','2026-09-01')").run();
  await f.p("INSERT INTO pvp_season_settlement_ranks VALUES(21,7,'challenger',1),(22,7,'challenger',1),(23,7,'grandmaster',10),(24,7,'challenger',21),(2,8,'challenger',1),(2,7,'challenger',20)").run();
