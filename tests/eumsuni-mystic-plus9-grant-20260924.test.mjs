 await db.exec(sql.slice(sql.indexOf('CREATE TABLE IF NOT EXISTS user_equipment_counts_v1'),sql.indexOf('-- ============================== 2. 경계 id')).replace(/GRANT SELECT, INSERT, UPDATE, DELETE ON user_equipment_counts_v1 TO cnine_migrator;/,''));
