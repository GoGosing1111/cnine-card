async function snapshot(db){const result={};for(const table of ['users','character_equipment_items','user_equipment_instances','equipment_forge_states_v1','user_equipment_counts_v1','user_equipment_loadout','app_meta','admin_logs'])result[table]=(await db.query(`SELECT * FROM ${table} ORDER BY 1,2`)).rows;return result;}

test('grants exactly three NEW +9 copies, preserves old +10/other items and loadout, counts once, and never replays twice',async()=>{
 const {db,client}=await fixture();try{
  const before=await snapshot(db),receipt=await grantEumsuniMysticPlus9(client),after=await snapshot(db);
  assert.deepEqual(receipt.items.map(item=>[item.id,item.level,item.quantity]),[[32,9,1],[34,9,1],[35,9,1]]);
  assert.deepEqual(receipt.countsBefore.map(row=>row.quantity),['1','1','0']);assert.deepEqual(receipt.countsAfter.map(row=>row.quantity),['2','2','1']);
  assert.equal(after.user_equipment_instances.length,before.user_equipment_instances.length+3);
  assert.deepEqual(after.user_equipment_instances.filter(row=>Number(row.id)<=4),before.user_equipment_instances);
  assert.deepEqual(after.equipment_forge_states_v1.filter(row=>Number(row.instance_id)<=4),before.equipment_forge_states_v1);
  assert.ok(after.equipment_forge_states_v1.filter(row=>Number(row.instance_id)>4).every(row=>row.level===9&&Number(row.user_id)===65));
  assert.deepEqual(after.users,before.users);assert.deepEqual(after.character_equipment_items,before.character_equipment_items);assert.deepEqual(after.user_equipment_loadout,before.user_equipment_loadout);
  assert.equal(after.admin_logs.length,1);assert.equal(after.app_meta.filter(row=>row.key===OPERATION_KEY).length,1);
  assert.equal((await grantEumsuniMysticPlus9(client)).replayed,true);assert.deepEqual(await snapshot(db),after);
 }finally{await db.close();}
});

test('enhancement or audit failure rolls all instances, enhanced levels, counts and receipt back together',async()=>{
 for(const fail of ['forge','audit']){const {db,client}=await fixture();try{
  await db.exec(fail==='forge'?"ALTER TABLE equipment_forge_states_v1 ADD CONSTRAINT forced_failure CHECK(level<>9)":"ALTER TABLE admin_logs ADD CONSTRAINT forced_failure CHECK(admin_id<0)");
  const before=await snapshot(db);await assert.rejects(grantEumsuniMysticPlus9(client),/forced_failure/);assert.deepEqual(await snapshot(db),before);
 }finally{await db.close();}}
});

