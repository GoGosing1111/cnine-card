import assert from 'node:assert/strict';
import test from 'node:test';
import {addApplicationFixture} from './helpers/supporter-application-fixture.mjs';
import {passFixture} from './helpers/supporter-pass-fixture.mjs';

for(const postgres of [false,true])test((postgres?'PostgreSQL':'SQLite')+' 시즌패스 구매 제한·미입금 거절 및 재시도',async t=>{
  const f=await addApplicationFixture(await passFixture({postgres}),{postgres});
  t.after(()=>f.close());
  const post=(body,user=1)=>f.call('admin/server-support',{user,body});
  const command=(action,userId,more={})=>({action,userId,expectedRevision:0,note:'미입금 확인',requestId:crypto.randomUUID(),...more});
  const order=(user,requestId=crypto.randomUUID())=>f.call('server-support/pass/purchase-request',{user,body:{requestId}});
  const info=async user=>(await f.call('server-support/info',{user})).body;
  const queue=async()=>(await f.call('admin/server-support/package/alerts')).body.passPending;
  const view=async id=>(await f.call('admin/server-support/preview',{body:{recipientType:'ID',recipient:String(id)}})).body;
  const raw=async id=>(await f.one('SELECT value FROM app_meta WHERE key=?','server_support_v1:'+id))?.value??null;
  assert.equal((await f.call('admin/server-support/pass',{body:{month:2,document:f.document(),expectedRevision:0,requestId:crypto.randomUUID()}})).status,200);
  assert.equal((await f.setting(true)).status,200);
  const request=crypto.randomUUID();
  assert.equal((await f.issue(2,request,{month:2})).status,200);
  const [original]=await queue();
  const reject=command('REJECT_UNPAID',2,{passApplicationId:original.id});
  assert.equal((await post(reject,3)).status,403);
  assert.equal((await post({...reject,userId:3})).status,400);
  assert.equal((await post({...reject,passApplicationId:'2_'+crypto.randomUUID()})).status,409);
  f.fail('INSERT INTO admin_logs');
  assert.equal((await post(reject)).status,503);
  f.fail('');
  assert.deepEqual(await queue(),[original]);
  const held=command('HOLD_PURCHASE',2,{expectedHoldRevision:0});
  assert.equal((await post(held)).body.purchaseHold.blocked,true);
  assert.equal((await post(held)).body.replayed,true);
  assert.deepEqual((await view(2)).purchaseHold,{blocked:true,revision:1});
  assert.equal((await post({...held,note:'changed'})).status,409);
  const blocked=await info(2);
  assert.equal(blocked.application.enabled,false);
  assert.equal(blocked.seasonPass.purchaseHeld,true);
  assert.equal(blocked.secondSeasonPass.canRequestPurchase,false);
  assert.equal(blocked.secondSeasonPass.purchasePending,true);
  for(const month of [1,2]){
    assert.equal((await f.issue(2,crypto.randomUUID(),{month})).body.code,'SUPPORT_PURCHASE_HELD');
    assert.equal((await post(command('GRANT',2,{month}))).body.code,'SUPPORT_PURCHASE_HELD');
  }
  assert.equal((await order(2)).body.code,'SUPPORT_PURCHASE_HELD');
  assert.equal((await raw(2)),null);
  const accepted=await post(reject);
  assert.equal(accepted.status,200);
  assert.deepEqual([accepted.body.status,accepted.body.reason,accepted.body.amountWon,accepted.body.passApplicationId],
    ['REJECTED','UNPAID',0,original.id]);
  assert.equal((await post(reject)).body.replayed,true);
  assert.equal((await post({...reject,requestId:crypto.randomUUID()})).status,409);
  assert.deepEqual(await queue(),[]);
  assert.equal((await raw(2)),null);
  const normal=await info(3);assert.equal(normal.application.enabled,true);assert.equal(normal.secondSeasonPass.canRequestPurchase,true);
  assert.equal((await post(command('RELEASE_PURCHASE',2,{expectedHoldRevision:0}))).status,409);
  const release=command('RELEASE_PURCHASE',2,{expectedHoldRevision:1});
  assert.deepEqual((await post(release)).body.purchaseHold,{blocked:false,revision:2});
  assert.equal((await post(release)).body.replayed,true);
  assert.equal((await order(2,request)).status,409);
  assert.equal((await f.issue(2,request,{month:2})).status,409);
  assert.deepEqual(await queue(),[]);
  const nextId=crypto.randomUUID(),next=(await order(2,nextId)).body.pending;
  assert.notEqual(next.id,original.id);
  assert.equal((await post(command('GRANT',2,{month:2,passApplicationId:original.id}))).status,409);
  assert.equal((await post({...reject,requestId:crypto.randomUUID()})).status,409);
  assert.equal((await queue())[0].id,next.id);
  assert.equal((await post(command('GRANT',2,{month:2,passApplicationId:next.id}))).status,200);
  assert.equal((await post(command('REJECT_UNPAID',2,{expectedRevision:1,passApplicationId:next.id}))).status,409);
  const paid=await raw(2);
  const rehold=command('HOLD_PURCHASE',2,{expectedRevision:1,expectedHoldRevision:2});
  assert.equal((await post(rehold)).status,200);
  assert.equal((await info(2)).secondSeasonPass.active,true);
  assert.equal(await raw(2),paid);
  assert.equal((await post(release)).body.replayed,true);
  assert.deepEqual((await view(2)).purchaseHold,{blocked:true,revision:3});
  const third=crypto.randomUUID(),thirdOrder=(await order(3,third)).body.pending;
  assert.equal((await post(command('REJECT_UNPAID',3,{passApplicationId:thirdOrder.id}))).status,200);
  assert.equal((await order(3,third)).status,409);
  assert.equal((await f.issue(3,third,{month:2})).status,409);
  assert.equal((await order(3)).status,200);
  const history=(await f.call('admin/server-support')).body.history;
  assert.equal(history.filter(r=>r.requestId===reject.requestId).length,1);
  assert.equal(history.filter(r=>r.requestId===held.requestId).length,1);
});
