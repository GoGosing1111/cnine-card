test('100억 and 1000억 bids debit and accumulate the exact amount once, including retries and refunds', async t => {
  const f = await auctionFixture(t);
  let total = 0;
  for (const amount of [10_000_000_000, 100_000_000_000]) {
    const id = 'large-' + amount, response = await f.bid(amount, id);
    total += amount;
    assert.equal(response.status, 200);
    assert.equal(response.body.state.mine.totalBid, total);
    assert.equal(f.row('SELECT coin FROM users').coin, 1_000_000_000_000 - total);
    assert.equal((await f.bid(amount, id)).body.replayed, true);
    assert.equal(f.row('SELECT coin FROM users').coin, 1_000_000_000_000 - total);
  }
  assert.equal(f.row('SELECT COUNT(*) n FROM coin_logs').n, 2);
  assert.equal(f.row('SELECT SUM(amount) amount FROM auction_coin_debits_v1574').amount, total);
  const refund = await f.request('auction/admin/cancel', {auctionId: 1});
  assert.equal(refund.body.refundTotal, total);
  assert.equal(f.row('SELECT coin FROM users').coin, 1_000_000_000_000);
  assert.equal((await f.request('auction/admin/cancel', {auctionId: 1})).status, 404);
  assert.equal(f.row('SELECT coin FROM users').coin, 1_000_000_000_000);
});

