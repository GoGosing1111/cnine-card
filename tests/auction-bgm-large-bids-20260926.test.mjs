test('previously queued non-BGM messages are omitted from the event stream', async t => {
  const f = await auctionFixture(t);
  await f.bid(500, 'old-silent');
  const silent = (await f.event('old-silent')).body.event;
  f.sql.prepare('INSERT INTO auction_bid_schedule_v1567(event_id,auction_id,starts_at,ends_at) VALUES(?,1,?,?)')
    .run(silent.id, new Date().toISOString(), new Date(Date.now() + 60000).toISOString());
  await f.bid(1000, 'new-bgm');
  const bgm = (await f.event('new-bgm')).body.event;
  await f.request('auction/schedule-event', {eventId: bgm.id});
  const events = (await f.request('auction/events?auctionId=1&after=0')).body.events;
  assert.deepEqual(events.map(event => event.id), [bgm.id]);
});

test('PostgreSQL executes 100억/1000억 bid SQL, rollback, retries and refunds without integer overflow', async t => {
  const f = await auctionFixture(t), pg = new PGlite();
  t.after(() => pg.close());
  const helpers = readFileSync(new URL('../scripts/postgres-runtime-compat.sql', import.meta.url), 'utf8');
  await pg.exec(helpers.slice(helpers.indexOf('CREATE OR REPLACE FUNCTION sqlite_datetime'), helpers.indexOf('CREATE OR REPLACE FUNCTION sqlite_date(')));
  await pg.exec("CREATE FUNCTION sqlite_now() RETURNS text LANGUAGE SQL STABLE AS $$SELECT to_char(timezone('UTC',CURRENT_TIMESTAMP),'YYYY-MM-DD HH24:MI:SS')$$;");
  // Match the existing PostgreSQL migration's 64-bit INTEGER mapping.
  for (const {name, sql} of f.sql.prepare("SELECT name,sql FROM sqlite_master WHERE type='table' AND name<>'sqlite_sequence'").all()) {
    await pg.exec(sql.replace(/INTEGER PRIMARY KEY AUTOINCREMENT/g, 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY')
      .replace(/\bINTEGER\b/g, 'BIGINT').replace(/CURRENT_TIMESTAMP/g, 'sqlite_now()'));
    for (const row of f.sql.prepare('SELECT * FROM ' + name).all()) {
      const entries = Object.entries(row);
      await pg.query(`INSERT INTO ${name}(${entries.map(([key]) => key).join(',')}) VALUES(${entries.map((_, i) => '$' + (i + 1)).join(',')})`, entries.map(([, value]) => value));
    }
  }
  let failLog = false;
  __postgresCompatTest.clearPostgresCatalogCache();
  f.env.DB = new __postgresCompatTest.PostgresD1Database({async query(input) {
    const text = typeof input === 'string' ? input : input.text;
    if (failLog && text.includes('INSERT INTO coin_logs')) throw Error('PostgreSQL rollback check');
    const result = await pg.query(text, typeof input === 'string' ? [] : input.values || []);
    const rows = result.rows.map(row => Object.fromEntries(Object.entries(row).map(([key, value]) => [key, typeof value === 'bigint' ? Number(value) : value])));
    return {...result, rows, rowCount: result.affectedRows ?? rows.length};
  }});
  const coin = async () => Number((await pg.query('SELECT coin FROM users WHERE id=1')).rows[0].coin);
  failLog = true;
  await assert.rejects(f.bid(100_000_000_000, 'pg-retry'), /PostgreSQL rollback check/);
  assert.equal(await coin(), 1_000_000_000_000);
  failLog = false;
  for (const [amount, id] of [[100_000_000_000, 'pg-retry'], [10_000_000_000, 'pg-second']]) {
    assert.equal((await f.bid(amount, id)).status, 200);
    assert.equal((await f.bid(amount, id)).body.replayed, true);
  }
  assert.equal(await coin(), 890_000_000_000);
  const receipt = (await pg.query('SELECT SUM(amount) amount,COUNT(*) count FROM auction_coin_debits_v1574')).rows[0];
  assert.equal(Number(receipt.amount), 110_000_000_000);
  assert.equal(Number(receipt.count), 2);
  assert.equal((await f.request('auction/admin/cancel', {auctionId: 1})).body.refundTotal, 110_000_000_000);
  assert.equal(await coin(), 1_000_000_000_000);
});

