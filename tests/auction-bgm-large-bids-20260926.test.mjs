test('insufficient funds and an interrupted large bid never leave a partial debit', async t => {
  const f = await auctionFixture(t);
  f.sql.exec('UPDATE users SET coin=1000000000');
  assert.equal((await f.bid(100_000_000_000, 'insufficient')).status, 409);
  assert.equal(f.row('SELECT coin FROM users').coin, 1_000_000_000);
  assert.equal(f.row('SELECT COUNT(*) n FROM auction_bidders_v1553').n, 0);
  f.sql.exec('UPDATE users SET coin=1000000000000');
  f.faults.sql = 'INSERT INTO coin_logs';
  await assert.rejects(f.bid(100_000_000_000, 'retry-transaction'), /injected transaction failure/);
  assert.equal(f.row('SELECT coin FROM users').coin, 1_000_000_000_000);
  assert.equal(f.row('SELECT COUNT(*) n FROM auction_bidders_v1553').n, 0);
  f.faults.sql = '';
  assert.equal((await f.bid(100_000_000_000, 'retry-transaction')).body.state.mine.totalBid, 100_000_000_000);
  await f.bid(100_000_000_000, 'retry-transaction');
  assert.equal(f.row('SELECT coin FROM users').coin, 900_000_000_000);
});

