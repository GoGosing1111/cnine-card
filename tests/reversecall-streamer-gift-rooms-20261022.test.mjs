// Exercise the shipped transaction against PostgreSQL with synthetic verification
// identities. No production provider identifiers are copied into test fixtures.
const dir=await mkdtemp(join(tmpdir(),'streamer-rooms-'));
const moduleUrl=new URL('../scripts/ops/reversecall-streamer-gift-rooms-20261022.mjs',import.meta.url);
const plan=JSON.parse(await readFile(new URL('./reversecall-streamer-gift-rooms-20261022.plan.json',moduleUrl),'utf8'));
for(const t of plan.targets)t.identityHash=createHash('sha256').update(JSON.stringify({provider:'TEST',providerId:'test-'+t.userId})).digest('hex');
await writeFile(join(dir,'reversecall-streamer-gift-rooms-20261022.plan.json'),JSON.stringify(plan));
await writeFile(join(dir,'reversecall-streamer-gift-rooms-20261022.source.json'),await readFile(new URL('./reversecall-streamer-gift-rooms-20261022.source.json',moduleUrl)));
const code=(await readFile(moduleUrl,'utf8')).replace('../../shared/reversecall-streamer-gift-v1.mjs',new URL('../shared/reversecall-streamer-gift-v1.mjs',import.meta.url).href);
await writeFile(join(dir,'grant.mjs'),code);
const ops=await import(pathToFileURL(join(dir,'grant.mjs')).href);
const {REVERSECALL_STREAMER_GIFT:gift}=await import('../shared/reversecall-streamer-gift-v1.mjs');
after(()=>{assert.equal(dirname(resolve(dir)),resolve(tmpdir()));assert(basename(dir).startsWith('streamer-rooms-'));return rm(dir,{recursive:true,force:true});});

async function fixture(){
 const db=new PGlite();
 await db.exec(`CREATE TABLE users(id BIGINT PRIMARY KEY,nickname TEXT,role TEXT,status TEXT,coin BIGINT DEFAULT 123,card_shards BIGINT DEFAULT 456,magic_crystals BIGINT DEFAULT 789);
  CREATE TABLE user_second_verifications(user_id BIGINT PRIMARY KEY,provider TEXT,provider_user_id TEXT);
  CREATE TABLE inventory_items(code TEXT PRIMARY KEY,name TEXT,is_active BIGINT,description TEXT);
  CREATE TABLE cnine_user_inventory(user_id BIGINT,item_code TEXT,quantity BIGINT,unseen_quantity BIGINT,created_at TEXT,updated_at TEXT,PRIMARY KEY(user_id,item_code));
  CREATE TABLE inventory_logs(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id BIGINT,item_code TEXT,change_amount BIGINT,balance_after BIGINT,reason TEXT,reference_type TEXT,reference_id TEXT,admin_id BIGINT,created_at TEXT);
  CREATE TABLE admin_logs(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,admin_id BIGINT,action_type TEXT,target_type TEXT,target_id TEXT,before_data TEXT,after_data TEXT,created_at TEXT);
  CREATE TABLE app_meta(key TEXT PRIMARY KEY,value TEXT,updated_at TEXT);
  INSERT INTO users(id,nickname,role,status) VALUES(1,'OWNER','OWNER','ACTIVE'),(4859,'암살자','USER','ACTIVE');
  INSERT INTO cnine_user_inventory VALUES(4859,'REVERSECALL_STREAMER_GIFT_BOX',4,1,'original','original');`);
 for(const t of ops.TARGETS){
  await db.query('INSERT INTO users(id,nickname,role,status) VALUES($1,$2,$3,$4)',[t.userId,t.nickname,t.role,'ACTIVE']);
  await db.query('INSERT INTO user_second_verifications VALUES($1,$2,$3)',[t.userId,'TEST','test-'+t.userId]);
  await db.query('INSERT INTO cnine_user_inventory VALUES($1,$2,8,3,$3,$3)',[t.userId,'OTHER_ITEM','original']);
 }
 await db.query('INSERT INTO inventory_items VALUES($1,$2,1,$3)',[gift.code,gift.name,gift.description]);
 await db.query('INSERT INTO cnine_user_inventory VALUES($1,$2,5,2,$3,$3)',[ops.IDS[0],gift.code,'original']);
 return db;
}
const options=dryRun=>({expectedPlanHash:ops.PLAN_HASH,lockDeadline:Date.now()+120000,dryRun});
async function snapshot(db){const out={};for(const table of ['users','user_second_verifications','inventory_items','cnine_user_inventory','inventory_logs','admin_logs','app_meta'])out[table]=(await db.query('SELECT * FROM '+table+' ORDER BY 1,2')).rows;return out;}

test('63 recipients get exactly 118 boxes, preserving existing inventory, wallets and the other assassin; retry never grants twice',async()=>{
 const db=await fixture();try{
  const before=await snapshot(db),dry=await ops.grant(db,options(true));assert.equal(dry.verification.totalBoxes,118);assert.deepEqual(await snapshot(db),before);
  const result=await ops.grant(db,options(false)),after=await snapshot(db);assert.equal(result.verification.recipientCount,63);
  assert.equal(after.inventory_logs.length,63);assert.equal(after.admin_logs.length,1);assert.equal(after.app_meta.length,1);
  for(const table of ['users','user_second_verifications','inventory_items'])assert.deepEqual(after[table],before[table]);
  const unrelated=r=>r.item_code!==gift.code||Number(r.user_id)===4859;assert.deepEqual(after.cnine_user_inventory.filter(unrelated),before.cnine_user_inventory.filter(unrelated));
  assert.equal(result.receipt.allocations.find(a=>a.userId==='4598').amount,2);assert.equal(result.receipt.allocations.find(a=>a.userId==='4562').amount,1);
  assert.deepEqual(result.receipt.roomCounts,{'조은이방':57,'봉순이방':61});
  assert.equal((await ops.grant(db,options(false))).replayed,true);assert.deepEqual(await snapshot(db),after);
  // A player may open a box after the grant. Immutable ledger verification must
  // still recognize the completed operation and must never restore that box.
  await db.query('UPDATE cnine_user_inventory SET quantity=quantity-1 WHERE user_id=$1 AND item_code=$2',[ops.IDS[0],gift.code]);
  const spent=await snapshot(db);assert.equal((await ops.grant(db,options(false))).replayed,true);assert.deepEqual(await snapshot(db),spent);
 }finally{await db.close();}
});

test('late ledger, audit and receipt failures roll back every recipient together',async()=>{
 const db=await fixture();try{
  for(const table of ['inventory_logs','admin_logs','app_meta']){
   await db.exec('ALTER TABLE '+table+' ADD CONSTRAINT fail_write CHECK(false)');const before=await snapshot(db);
   await assert.rejects(ops.grant(db,options(false)),/fail_write/);assert.deepEqual(await snapshot(db),before);await db.exec('ALTER TABLE '+table+' DROP CONSTRAINT fail_write');
  }
  assert.equal((await ops.grant(db,options(false))).verification.totalBoxes,118);
 }finally{await db.close();}
});

test('changed identity, inactive catalog, invalid plan and expired leases block the whole operation',async()=>{
 const db=await fixture();try{
  for(const [setup,restore] of [
   ["UPDATE user_second_verifications SET provider_user_id='changed' WHERE user_id=4598","UPDATE user_second_verifications SET provider_user_id='test-4598' WHERE user_id=4598"],
   ["UPDATE inventory_items SET is_active=0","UPDATE inventory_items SET is_active=1"],
   ["UPDATE users SET nickname='renamed' WHERE id=4562","UPDATE users SET nickname='찡찡ෆ' WHERE id=4562"]
  ]){await db.exec(setup);const before=await snapshot(db);await assert.rejects(ops.grant(db,options(false)));assert.deepEqual(await snapshot(db),before);await db.exec(restore);}
  await assert.rejects(ops.grant(db,{...options(false),expectedPlanHash:'wrong'}),/Reviewed plan/);
  await assert.rejects(ops.grant(db,{...options(false),lockDeadline:Date.now()-1}),/leases/);
 }finally{await db.close();}
});

test('unsafe quantities and orphan ledgers are never credited again',async()=>{
 const db=await fixture();try{
  await db.query('UPDATE cnine_user_inventory SET quantity=$1 WHERE user_id=$2 AND item_code=$3',[Number.MAX_SAFE_INTEGER,ops.IDS[0],gift.code]);
  const unsafe=await snapshot(db);await assert.rejects(ops.grant(db,options(false)),/Unsafe inventory/);assert.deepEqual(await snapshot(db),unsafe);
  await db.query('UPDATE cnine_user_inventory SET quantity=5 WHERE user_id=$1 AND item_code=$2',[ops.IDS[0],gift.code]);
  await db.query('INSERT INTO inventory_logs(user_id,item_code,reference_id) VALUES($1,$2,$3)',[ops.IDS[0],gift.code,ops.OPERATION_KEY]);
  const orphan=await snapshot(db);await assert.rejects(ops.grant(db,options(false)),/Orphan grant/);assert.deepEqual(await snapshot(db),orphan);
 }finally{await db.close();}
});
