import test from 'node:test';
import assert from 'node:assert/strict';
import {PGlite} from '@electric-sql/pglite';
import {PASS_KEY,emptyPass} from '../shared/supporter-season-pass-v1.mjs';
import {applyPassSalesStart,verifyPassSalesStart,OPERATION_KEY,SALES_STARTS_AT,SALES_AUDIT_ID} from '../scripts/ops/supporter-pass-sales-start-20261020.mjs';

async function fixture(){
  const db=new PGlite();
  await db.exec(`CREATE TABLE app_meta(key TEXT PRIMARY KEY,value TEXT,updated_at TEXT);
    CREATE TABLE users(id INTEGER PRIMARY KEY,nickname TEXT,role TEXT,status TEXT,coin BIGINT);
    CREATE TABLE admin_logs(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,admin_id INTEGER,action_type TEXT,target_type TEXT,target_id TEXT,before_data TEXT,after_data TEXT,created_at TEXT);
    INSERT INTO users VALUES(1,'핑크빛유두','OWNER','ACTIVE',1234);
    INSERT INTO app_meta VALUES('server_support_v1:1','{"startsAt":1791800000000,"endsAt":1794392000000}','keep');
    INSERT INTO app_meta VALUES('supporter_pass_claim_v1:1:1791800000000-0:1','{"day":1}','keep');`);
  const config={...emptyPass(),revision:16,enabled:true,writeToken:'old-token'};
  config.days[0].rewards=[{type:'COIN',quantity:123456,name:'코인',image:''}];
  await db.query('INSERT INTO app_meta VALUES($1,$2,$3)',[PASS_KEY,JSON.stringify(config),'keep']);
  await db.query('INSERT INTO admin_logs(id,action_type,before_data,after_data) VALUES($1,$2,$3,$4)',[
    SALES_AUDIT_ID,'SERVER_SUPPORT_APPLICATION_SETTINGS',JSON.stringify({enabled:false,revision:0}),
    JSON.stringify({config:{enabled:true,revision:1},processedAt:SALES_STARTS_AT})
  ]);
  return db;
}
async function snapshot(db){return Object.fromEntries(await Promise.all(['users','app_meta','admin_logs'].map(async t=>[t,(await db.query('SELECT * FROM '+t+' ORDER BY 1')).rows])));}

test('sales anchor is atomic, idempotent and preserves rewards, subscriptions and existing receipts',async()=>{
  const db=await fixture();
  try{
    const before=await snapshot(db),result=await applyPassSalesStart(db),after=await snapshot(db);
    assert.equal((await verifyPassSalesStart(db)).verified,true);
    assert.equal(result.receipt.after.salesStartsAt,SALES_STARTS_AT);
    assert.equal(result.receipt.after.revision,17);
    assert.deepEqual(result.receipt.after.days,result.receipt.before.days);
    assert.equal(result.receipt.after.enabled,result.receipt.before.enabled);
    assert.deepEqual(after.users,before.users);
    assert.deepEqual(after.app_meta.filter(r=>![PASS_KEY,OPERATION_KEY].includes(r.key)),before.app_meta.filter(r=>r.key!==PASS_KEY));
    assert.equal((await applyPassSalesStart(db)).alreadyApplied,true);assert.deepEqual(await snapshot(db),after);
    const changed={...result.receipt.after,revision:18,title:'운영자 이후 변경'};
    await db.query('UPDATE app_meta SET value=$1 WHERE key=$2',[JSON.stringify(changed),PASS_KEY]);
    assert.equal((await applyPassSalesStart(db)).alreadyApplied,true);
    assert.deepEqual(JSON.parse((await db.query('SELECT value FROM app_meta WHERE key=$1',[PASS_KEY])).rows[0].value),changed);
  }finally{await db.close();}
});
test('dry run, incorrect sales evidence and audit failure cannot partly activate the anchor',async()=>{
  const db=await fixture();
  try{
    const before=await snapshot(db);assert.equal((await applyPassSalesStart(db,{dryRun:true})).dryRun,true);
    assert.deepEqual(await snapshot(db),before);
    const original=db.query.bind(db);
    const client={query:async(q,args)=>{if(q.startsWith('INSERT INTO admin_logs'))throw Error('Audit unavailable');return original(q,args);}};
    await assert.rejects(applyPassSalesStart(client),/Audit unavailable/);assert.deepEqual(await snapshot(db),before);
    await db.query('UPDATE admin_logs SET after_data=$1 WHERE id=$2',[JSON.stringify({config:{enabled:true,revision:1},processedAt:SALES_STARTS_AT+1}),SALES_AUDIT_ID]);
    const changed=await snapshot(db);await assert.rejects(applyPassSalesStart(db));assert.deepEqual(await snapshot(db),changed);
  }finally{await db.close();}
});
