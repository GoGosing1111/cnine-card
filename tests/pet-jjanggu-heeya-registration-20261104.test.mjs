test('registration plan adds only the approved Jjanggu Heeya definition with the reviewed Heukgu options',async t=>{
  const {state}=await fixture(t),before=structuredClone(state),plan=planRegistration(state,validatePetCmsDocument);
  assert.deepEqual(state,before,'planning must not mutate the inspected state');
  assert.deepEqual(plan.document.pets.slice(0,25),state.document.pets);
  assert.deepEqual(plan.document.pets.slice(25).map(p=>[p.code,p.name]),[
    ['PET-JJANGGU-HEEYA','짱구희야'],
  ]);
  for(const pet of plan.document.pets.slice(25)){
    assert.equal(pet.sourceArt,'assets/ui/pets/jjanggu-heeya-20261104/pet-jjanggu-heeya-approved.png');
    for(const key of ["enabled","liveEnabled","modes","target","buffs","rewardBonuses"])assert.deepEqual(pet[key],state.document.pets.at(-1)[key],key);
  }
  assert.throws(()=>planRegistration({...state,document:plan.document},validatePetCmsDocument),/Jjanggu Heeya entry already exists/);
});

test('default rollback leaves CMS, audit, receipts, account records and inventory unchanged',async t=>{
  const f=await fixture(t),before=await f.snapshot();
  const result=await registerJjangguHeeya(f.db,f.options);
  assert.equal(result.committed,false);assert.equal(result.replayed,false);
  assert.equal(result.verification.verified,true);assert.equal(result.verification.petCount,26);
  assert.deepEqual(await f.snapshot(),before);
  assert.equal((await inspect(f.db)).receipt,null);
});

test('successful registration preserves all existing pets and unrelated state in one audited revision',async t=>{
  const f=await fixture(t),before=await f.snapshot();
  const result=await registerJjangguHeeya(f.db,{...f.options,commit:true});
  assert.equal(result.committed,true);assert.equal(result.replayed,false);
  assert.equal(result.receipt.previousRevision,29);assert.equal(result.receipt.revision,30);
  assert.equal(result.receipt.preservedRows,25);assert.equal(result.receipt.accountGrants,0);
  assert.equal(result.receipt.openingPoolChanged,false);assert.equal(result.receipt.potentialSettingsChanged,false);
  assert.equal(result.receipt.liveEffectsEnabled,true);
  const current=await inspect(f.db),after=await f.snapshot();
  assert.deepEqual(current.state.document,{...f.state.document,pets:[...f.state.document.pets,...additions]});
  assert.deepEqual(current.state.audit.slice(1),f.state.audit);
  assert.equal(current.state.audit.filter(a=>a.requestId===REQUEST_ID).length,1);
  assert.equal(current.state.updatedBy,7);assert.equal(current.state.revision,30);
  assert.equal(current.state.audit[0].payloadHash,hash(JSON.stringify(['7',29,current.state.document])));
  assert.deepEqual(after.meta.filter(r=>r.key!==CMS_KEY&&r.key!==OP),before.meta.filter(r=>r.key!==CMS_KEY));
  assert.deepEqual(after.inventory,before.inventory);assert.deepEqual(after.users,before.users);
  assert.equal(after.logs.length,1);assert.equal(after.logs[0].action_type,ACTION);
  assert.deepEqual(after.logs[0].before_data,f.state);
  assert.deepEqual(current.receipt,result.receipt);
  assert.equal((await verifyRegistration(f.db,result.receipt,{exact:true})).verified,true);
});

test('stale revision or raw content hash rejects the operation without writes',async t=>{
  const f=await fixture(t),before=await f.snapshot();
  await assert.rejects(registerJjangguHeeya(f.db,{...f.options,expectedRevision:28,commit:true}),/CMS revision changed/);
  assert.deepEqual(await f.snapshot(),before);
  await assert.rejects(registerJjangguHeeya(f.db,{...f.options,expectedRawHash:'0'.repeat(64),commit:true}),/CMS content changed/);
  assert.deepEqual(await f.snapshot(),before);
});

test('receipt insertion failure rolls back the preceding CMS update and audit insert',async t=>{
  const f=await fixture(t);
  await f.db.exec(`ALTER TABLE app_meta ADD CONSTRAINT reject_pepegu_receipt CHECK(key <> '${OP}')`);
  const before=await f.snapshot();
  await assert.rejects(registerJjangguHeeya(f.db,{...f.options,commit:true}),/reject_pepegu_receipt/);
  assert.deepEqual(await f.snapshot(),before);
  assert.equal((await inspect(f.db)).receipt,null);
});

test('idempotent replay returns the same verified receipt and performs no extra writes',async t=>{
  const f=await fixture(t),saved=await registerJjangguHeeya(f.db,{...f.options,commit:true});
  const before=await f.snapshot(),writes=[];
  const traced={async query(sql,args){assert.match(sql,/^SELECT\b/,'Replay must be SELECT-only');if(!/^SELECT\b/.test(sql))writes.push(sql);return f.db.query(sql,args);}};
  const replay=await registerJjangguHeeya(traced,{...f.options,commit:true});
  assert.equal(replay.replayed,true);assert.equal(replay.committed,true);
  assert.deepEqual(replay.receipt,saved.receipt);assert.equal(replay.verification.verified,true);
  assert.deepEqual(writes,[]);assert.deepEqual(await f.snapshot(),before);
});

