async function commitGrant(db,options){await db.exec('BEGIN');try{const result=await grant(db,options);await db.exec('COMMIT');return result;}catch(e){await db.exec('ROLLBACK');throw e;}}
const selectOnly=db=>({query:(sql,args)=>{assert.match(sql,/^SELECT\b/);return db.query(sql,args);}});
test('two 1000 authorizations grant 2000 exactly once, preserving all unrelated state',async()=>{
 const {db,options}=await fixture();try{
  const before=await snapshot(db),result=await commitGrant(db,options);
  assert.deepEqual(PLAN.requestParts,[1000,1000]);assert.equal(result.receipt.pig.before,'0');assert.equal(result.receipt.pig.after,'2000');
  assert.equal(result.receipt.syncAfter.revision,'21');assert.deepEqual(protectedState(await snapshot(db)),protectedState(before));await verify(db,undefined,{exact:true});
  const replay=await grant(selectOnly(db));assert(replay.replayed);assert.deepEqual(replay.receipt,result.receipt);assert.equal((await artifacts(db)).pig.length,1);assert.equal((await artifacts(db)).audit.length,1);
 }finally{await db.close();}
});
