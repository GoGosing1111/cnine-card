test('exact one-card grant is atomic, replayable, isolated from public issuance, and rejects a wrong account identity',async t=>{
 const db=new PGlite();t.after(()=>db.close());
 await db.exec(`CREATE TABLE users(id bigint primary key,nickname text,role text,status text);
 CREATE TABLE app_meta(key text primary key,value text,updated_at text);
 CREATE TABLE user_mercenary_cards_v1(user_id bigint,mercenary_code text,total_copies int,duplicate_count int,first_obtained_at text,last_obtained_at text,primary key(user_id,mercenary_code));
 CREATE TABLE mercenary_card_acquisitions_v1(acquisition_id text primary key,user_id bigint,mercenary_code text,is_duplicate int,total_copies_after int,duplicate_count_after int,created_at text);
 CREATE TABLE mercenary_limited_stock_v1(code text primary key,issued int,stock_limit int);
 CREATE TABLE mercenary_limited_issues_v1(code text,serial int);
 CREATE TABLE admin_logs(id bigint generated by default as identity primary key,admin_id bigint,action_type text,target_type text,target_id text,before_data text,after_data text);
 INSERT INTO users VALUES(1,'핑크빛유두','OWNER','ACTIVE');
 INSERT INTO mercenary_limited_stock_v1 VALUES('V-999',2,10);
 INSERT INTO mercenary_limited_issues_v1 VALUES('V-999',1),('V-999',2);`);
 const original=await inspectJinmuGrant(db);
 assert.equal((await grantJinmuOwner(db,{dryRun:true})).status,'VERIFIED');
 assert.deepEqual(await inspectJinmuGrant(db),original);
 let inserted=false;
 const failed={query:async(sql,args)=>{if(sql.startsWith('INSERT INTO admin_logs')){inserted=true;throw Error('INJECTED_FAILURE');}return db.query(sql,args);}};
 await assert.rejects(grantJinmuOwner(failed),/INJECTED_FAILURE/);assert.equal(inserted,true);assert.deepEqual(await inspectJinmuGrant(db),original);
 const first=await grantJinmuOwner(db),second=await grantJinmuOwner(db);
 assert.equal(first.replayed,false);assert.equal(second.replayed,true);
 assert.equal(second.holders.length,1);assert.equal(second.holders[0].total_copies,1);
 assert.equal(second.limitedDigest,original.limitedDigest);
 assert.equal((await db.query('SELECT * FROM mercenary_card_acquisitions_v1')).rows.length,1);
 assert.equal((await db.query('SELECT * FROM admin_logs')).rows.length,1);
 assert.equal(second.receipt.operationKey,OPERATION_KEY);
 await db.query("UPDATE users SET nickname='different' WHERE id=1");
 await assert.rejects(grantJinmuOwner(db));assert.equal((await db.query('SELECT total_copies FROM user_mercenary_cards_v1')).rows[0].total_copies,1);
});
