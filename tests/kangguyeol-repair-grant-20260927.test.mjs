import test from 'node:test';
import assert from 'node:assert/strict';
import {PGlite} from '@electric-sql/pglite';
import {grantKangGuyeolRepairCoupon,OPERATION_KEY,TARGET,ITEM_CODE,ITEM_NAME} from '../scripts/ops/kangguyeol-repair-grant-20260927.mjs';

async function fixture(){
 const db=new PGlite();
 await db.exec(`CREATE TABLE users(id BIGINT PRIMARY KEY,nickname TEXT,role TEXT,status TEXT,coin BIGINT DEFAULT 123,card_shards BIGINT DEFAULT 456,magic_crystals BIGINT DEFAULT 789);
  INSERT INTO users(id,nickname,role,status) VALUES(1,'관리자','OWNER','ACTIVE'),(4718,'강구열','USER','ACTIVE'),(66,'다른 계정','USER','ACTIVE');
  CREATE TABLE inventory_items(code TEXT PRIMARY KEY,name TEXT,is_active BIGINT);
  CREATE TABLE cnine_user_inventory(user_id BIGINT,item_code TEXT,quantity BIGINT,unseen_quantity BIGINT,created_at TEXT,updated_at TEXT,PRIMARY KEY(user_id,item_code));
  CREATE TABLE inventory_logs(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,user_id BIGINT,item_code TEXT,change_amount BIGINT,balance_after BIGINT,reason TEXT,reference_type TEXT,reference_id TEXT,admin_id BIGINT,created_at TEXT);
  CREATE TABLE admin_logs(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,admin_id BIGINT,action_type TEXT,target_type TEXT,target_id TEXT,before_data TEXT,after_data TEXT,created_at TEXT);
  CREATE TABLE app_meta(key TEXT PRIMARY KEY,value TEXT,updated_at TEXT);
  INSERT INTO cnine_user_inventory VALUES(4718,'PINGDU_REPAIR_COUPON',2,0,'original','original'),(4718,'MASTER_STAR',900,5,'original','original'),(66,'PINGDU_REPAIR_COUPON',7,1,'original','original');`);
 await db.query('INSERT INTO inventory_items VALUES($1,$2,1)',[ITEM_CODE,ITEM_NAME]);
 return {db,client:{async query(sql,args=[]){const r=await db.query(sql,args);return {...r,rowCount:r.affectedRows??r.rows.length};}}};
}
async function snapshot(db){const result={};for(const table of ['users','inventory_items','cnine_user_inventory','inventory_logs','admin_logs','app_meta'])result[table]=(await db.query(`SELECT * FROM ${table} ORDER BY 1,2`)).rows;return result;}

test('increments only the target coupon by two and retries never grant twice, with existing or missing inventory',async()=>{
 for(const existing of [true,false]){
  const {db,client}=await fixture();try{
   if(!existing)await db.query('DELETE FROM cnine_user_inventory WHERE user_id=$1 AND item_code=$2',[TARGET.id,ITEM_CODE]);
   const before=await snapshot(db);assert.equal((await grantKangGuyeolRepairCoupon(client,{dryRun:true})).dryRun,true);assert.deepEqual(await snapshot(db),before);
   const receipt=await grantKangGuyeolRepairCoupon(client),after=await snapshot(db);
   assert.equal(receipt.amount,2);assert.equal(receipt.after.quantity,existing?'4':'2');assert.equal(receipt.after.unseenQuantity,'2');
   assert.equal(receipt.before.quantity,existing?'2':'0');
   const unrelated=row=>Number(row.user_id)!==TARGET.id||row.item_code!==ITEM_CODE;
   assert.deepEqual(after.cnine_user_inventory.filter(unrelated),before.cnine_user_inventory.filter(unrelated));
   for(const key of ['users','inventory_items'])assert.deepEqual(after[key],before[key]);
   assert.equal(after.inventory_logs.length,1);assert.equal(Number(after.inventory_logs[0].change_amount),2);
   assert.equal(after.inventory_logs[0].reference_id,OPERATION_KEY);assert.equal(after.admin_logs.length,1);assert.equal(after.app_meta.length,1);
   assert.equal((await grantKangGuyeolRepairCoupon(client)).replayed,true);assert.deepEqual(await snapshot(db),after);
  }finally{await db.close();}
 }
});
test('ledger, audit or receipt failures roll back the grant and allow one successful retry',async()=>{
 for(const table of ['inventory_logs','admin_logs','app_meta']){
  const {db,client}=await fixture();try{
   await db.exec(`ALTER TABLE ${table} ADD CONSTRAINT forced_failure CHECK(false)`);
   const before=await snapshot(db);await assert.rejects(grantKangGuyeolRepairCoupon(client),/forced_failure/);assert.deepEqual(await snapshot(db),before);
   await db.exec(`ALTER TABLE ${table} DROP CONSTRAINT forced_failure`);
   assert.equal((await grantKangGuyeolRepairCoupon(client)).after.quantity,'4');
   assert.equal((await grantKangGuyeolRepairCoupon(client)).replayed,true);
  }finally{await db.close();}
 }
});
