test('Bazzi V3 bytes survive unchanged and owned equipment resolves in PVE/PVP',async t=>{
 const bytes=await readFile(new URL('../'+approval.approvedAsset,import.meta.url));
 assert.equal(createHash('sha256').update(bytes).digest('hex'),approval.sha256);
 assert.deepEqual(bytes,await readFile(new URL('../'+approval.sourceAsset,import.meta.url)));
 const f=await petLiveFixture(t),state=await f.record('pet_cms_preparation_v1');
 state.document.visibility='LIVE';state.document.battleEnabled=true;
 const plan=planPetRegistration(state);assert.deepEqual(plan.document.pets.slice(0,-1),state.document.pets);
 await f.write('pet_cms_preparation_v1',{...state,document:plan.document});
 const save={petCode:addition.code,expectedRevision:0,petCmsRevision:state.revision,requestId:crypto.randomUUID()};
 assert.equal((await f.call('pets/v1/loadout',{body:save})).status,403);
 await f.write('pet_collection_v1:2',{revision:1,pets:{[addition.code]:1}});
 assert.equal((await f.call('pets/v1/loadout',{body:{...save,requestId:crypto.randomUUID()}})).status,200);
 const cards=REVIEW_DECK.map(c=>({...c,rarity:c.grade,basePower:c.power,power:c.power*10}));
 for(const mode of ['PVE','PVP']){
  const pet=await loadPetBattleSnapshot(f.env,2,mode);assert.equal(pet.definition.code,addition.code);
  const battle=mode==='PVE'?createPveBattleV2({cards,pet,monster:{id:1,battle_power:1800000},seed:37}):createPvpBattleV2({attackerCards:cards,defenderCards:cards,attackerPet:pet,defenderPet:pet,seed:37});
  const events=battle.result.timeline.filter(e=>e.type==='PET_OPENING_BUFF');
  assert.equal(events.length,mode==='PVE'?1:2);
  assert(events.every(e=>e.name===addition.name&&e.battleSprite===approval.approvedAsset));
 }
});

test('registration is revision-locked, preserves old pets/settings, rolls back failures and replays once',async t=>{
 const pg=new PGlite();t.after(()=>pg.close());
 await pg.exec("CREATE TABLE app_meta(key TEXT PRIMARY KEY,value TEXT,updated_at TEXT);CREATE TABLE users(id INT,role TEXT,status TEXT);INSERT INTO users VALUES(9,'OWNER','ACTIVE');CREATE TABLE admin_logs(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,admin_id INT,action_type TEXT,target_type TEXT,target_id TEXT,before_data TEXT,after_data TEXT);");
 const old=approval.runtime.preservedExistingCodes.map(code=>({...addition,code,name:code,buffs:[{type:'DEFENSE_PERCENT',percent:25}],rewardBonuses:{dropPercent:3,accountXpPercent:5,coinPercent:7}}));
 const state={revision:11,audit:[],document:{version:1,visibility:'LIVE',battleEnabled:true,acquisitionEnabled:false,pets:old}};
 const protectedRecords={'pet_opening_settings_v1':{enabled:false,pool:[]},'pet_potential_settings_v1':{enabled:false},'pet_collection_v1:2':{revision:1,pets:{'PET-NAMUNEUL-BONGSOON':2}}};
 for(const [key,value] of Object.entries({'pet_cms_preparation_v1':state,...protectedRecords}))await pg.query('INSERT INTO app_meta VALUES($1,$2,NULL)',[key,JSON.stringify(value)]);
 const snapshot=async()=>({meta:(await pg.query('SELECT * FROM app_meta ORDER BY key')).rows,audits:(await pg.query('SELECT * FROM admin_logs ORDER BY id')).rows});
 const before=await snapshot();
 await assert.rejects(registerApprovedPet(pg,{expectedRevision:10,commit:true}),/CMS changed/);assert.deepEqual(await snapshot(),before);
 const dry=await registerApprovedPet(pg,{expectedRevision:11});assert.equal(dry.committed,false);assert.deepEqual(await snapshot(),before);
 const failing={query:(sql,args)=>sql.startsWith('INSERT INTO admin_logs')?Promise.reject(Error('Audit unavailable')):pg.query(sql,args)};
 await assert.rejects(registerApprovedPet(failing,{expectedRevision:11,commit:true}),/Audit unavailable/);assert.deepEqual(await snapshot(),before);
 const saved=await registerApprovedPet(pg,{expectedRevision:11,commit:true});assert.equal(saved.revision,12);assert.equal(saved.committed,true);
 const replay=await registerApprovedPet(pg,{expectedRevision:11,commit:true});assert.equal(replay.replayed,true);assert.equal(replay.auditId,saved.auditId);
 const after=await snapshot(),records=Object.fromEntries(after.meta.map(r=>[r.key,JSON.parse(r.value)]));
 assert.deepEqual(records.pet_cms_preparation_v1.document.pets,[...old,addition]);
 assert.equal(records.pet_cms_preparation_v1.audit.length,1);assert.equal(after.audits.length,1);assert.equal(records[OPERATION_KEY].addedCode,addition.code);
 for(const [key,value] of Object.entries(protectedRecords))assert.deepEqual(records[key],value);
});
