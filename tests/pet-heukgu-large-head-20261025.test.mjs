 assert.deepEqual(state.document.pets.filter(p=>p.code!=='PET-HEUKGU'),recorded.document.pets.filter(p=>p.code!=='PET-HEUKGU'));
 assert.deepEqual(after.meta.filter(r=>![CMS_KEY,OP].includes(r.key)),before.meta.filter(r=>r.key!==CMS_KEY));
