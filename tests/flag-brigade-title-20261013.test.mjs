async function fixture(t,postgres){
 let DB,pg,sqlite,fail=()=>false;
 if(postgres){
  pg=new PGlite();await pg.exec("CREATE FUNCTION sqlite_now() RETURNS text LANGUAGE SQL STABLE AS $$SELECT to_char(timezone('UTC',CURRENT_TIMESTAMP),'YYYY-MM-DD HH24:MI:SS')$$;");
  await pg.exec(schema.replaceAll('INTEGER PRIMARY KEY AUTOINCREMENT','BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY'));
  DB=new __postgresCompatTest.PostgresD1Database({async query(input){const sql=typeof input==='string'?input:input.text,args=typeof input==='string'?[]:input.values||[];if(fail(sql,args))throw Error('INJECTED_FAILURE');const r=await pg.query(sql,args);return {...r,rowCount:r.affectedRows??r.rows.length};}});
 }else{
  sqlite=new DatabaseSync(':memory:');sqlite.exec(schema);
  const prepare=(sql,args=[])=>({
   bind(...v){return prepare(sql,v)},
   async first(){return sqlite.prepare(sql).get(...args)||null},
   async all(){return {results:sqlite.prepare(sql).all(...args)}},
   async run(){
    if(fail(sql,args))throw Error('INJECTED_FAILURE');
    return {meta:{changes:Number(sqlite.prepare(sql).run(...args).changes)}};
   }
  });
  DB={prepare,async batch(rows){sqlite.exec('BEGIN');try{const result=[];for(const row of rows)result.push(await row.run());sqlite.exec('COMMIT');return result;}catch(e){sqlite.exec('ROLLBACK');throw e;}}};
 }
 t.after(()=>pg?pg.close():sqlite.close());
 const env={DB},p=(sql,...args)=>DB.prepare(sql).bind(...args);
 // This focused route fixture supplies the current title schema; unrelated
 // equipment/suit migrations are outside this catalogue addition.
 const prepare=DB.prepare.bind(DB);
 DB.prepare=sql=>sql.startsWith('SELECT key,value FROM app_meta WHERE key IN')?{bind(...keys){return{async all(){return{results:keys.map(key=>({key,value:'1'}))}}}}}:prepare(sql);
 const call=(path,body,user)=>handleEquipment({path,env,request:new Request('https://game.test/api/'+path,{method:'POST',body:JSON.stringify(body)}),deps:{authenticate:async()=>user,readBody:r=>r.json(),json:(body,status=200)=>({status,body})}});
 return {env,p,call,fail:fn=>{fail=fn}};
}
