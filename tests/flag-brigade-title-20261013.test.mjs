 test(`${label}: both 30 official victories and 8000 personal duel wins are required, without replay grants or auto-equip`,async t=>{
  const f=await fixture(t,postgres);await ensureFlagBrigadeTitle(f.env);await f.p('INSERT INTO users VALUES(8),(9)').run();
  await f.p(`WITH RECURSIVE n(x) AS(SELECT 1 UNION ALL SELECT x+1 FROM n WHERE x<30)
    INSERT INTO territory_war_v3_rounds SELECT x,'FINISHED','A','2026-10-13 00:00:00' FROM n`).run();
  await f.p("INSERT INTO territory_war_v3_users SELECT id,8,'A' FROM territory_war_v3_rounds").run();
  await f.p("INSERT INTO territory_war_v3_rewards SELECT id,8,'A','WIN' FROM territory_war_v3_rounds").run();
  await f.p(`WITH RECURSIVE n(x) AS(SELECT 1 UNION ALL SELECT x+1 FROM n WHERE x<7999)
    INSERT INTO territory_war_v3_actions SELECT x,'battle-'||x,1,8,9,'A','A','COMPLETED' FROM n`).run();
  assert.deepEqual(await readTerritoryVictories(f.env,8),{roundWins:30,battleWins:7999});
  let result=await syncFlagBrigadeTitle(f.env,8);assert.deepEqual(result.granted,[]);assert.equal(result.progress.FLAG_BRIGADE.complete,false);
  // A committed defence victory completes the personal requirement.
  await f.p("INSERT INTO territory_war_v3_actions VALUES(8000,'defence',1,9,8,'B','A','APPLIED')").run();
  await f.p("UPDATE territory_war_v3_rewards SET result='INELIGIBLE' WHERE round_id=30").run();
  result=await syncFlagBrigadeTitle(f.env,8);assert.deepEqual(result.granted,[]);assert.equal(result.progress.FLAG_BRIGADE.roundWins,29);assert.equal(result.progress.FLAG_BRIGADE.battleWins,8000);
  await f.p("UPDATE territory_war_v3_rewards SET result='WIN' WHERE round_id=30").run();
  // Pending/failed, losses, draws, self matches, and side mismatches add nothing.
  await f.p(`INSERT INTO territory_war_v3_actions VALUES
    (8001,'pending',1,8,9,'A','A','PENDING'),(8002,'failed',1,8,9,'A','A','FAILED'),
    (8003,'loss',1,8,9,'A','B','COMPLETED'),(8004,'draw',1,8,9,'A','DRAW','COMPLETED'),
    (8005,'self',1,8,8,'A','A','COMPLETED'),(8006,'invalid-side',1,8,9,'B','B','COMPLETED')`).run();
  assert.deepEqual(await readTerritoryVictories(f.env,8),{roundWins:30,battleWins:8000});
  await f.p("UPDATE territory_war_v3_actions SET status='COMPLETED' WHERE request_id='defence'").run();
  assert.deepEqual(await readTerritoryVictories(f.env,8),{roundWins:30,battleWins:8000},'APPLIED completion is the same duel');
  await assert.rejects(()=>f.p("INSERT INTO territory_war_v3_actions VALUES(9000,'defence',1,9,8,'B','A','COMPLETED')").run(),/UNIQUE|duplicate/i);
  const id=Number((await f.p('SELECT id FROM character_titles').first()).id);
  assert.equal((await f.call('character/title/equip',{titleId:id},{id:8,role:'USER'})).status,404);
  result=await syncFlagBrigadeTitle(f.env,8);assert.deepEqual(result.granted,[id]);assert.equal(result.progress.FLAG_BRIGADE.complete,true);
  assert.deepEqual((await syncFlagBrigadeTitle(f.env,8)).granted,[]);
  assert.equal(Number((await f.p('SELECT COUNT(*) n FROM user_character_titles').first()).n),1);
  assert.equal(Number((await f.p('SELECT COUNT(*) n FROM user_title_loadout').first()).n),0);
  await f.p('INSERT INTO user_title_loadout(user_id,title_id) VALUES(?,?)',8,id).run();
  const titles=await publicEquippedTitleMap(f.env,[8,9]);assert.equal(titles['8'].stylePreset,'FLAG_BRIGADE');assert.equal(titles['8'].image,'/assets/ui/titles/flag-brigade-v1.webp');assert.equal(titles['9'],undefined);
 });
