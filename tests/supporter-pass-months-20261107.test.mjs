import test from 'node:test';
import assert from 'node:assert/strict';
import {passFixture} from './helpers/supporter-pass-fixture.mjs';
import {addApplicationFixture} from './helpers/supporter-application-fixture.mjs';
import {PASS_KEY,DAY_MS,claimKey,passConfigKey} from '../shared/supporter-season-pass-v1.mjs';

for(const postgres of [false,true])test(`${postgres?'PostgreSQL':'SQLite'}: 월별 패스 구매와 수령`,async t=>{
  const f=await addApplicationFixture(await passFixture({postgres}),{postgres});
  t.after(()=>f.close());
  const info=async user=>(await f.call('server-support/info',{user})).body;
  const raw=async key=>(await f.one('SELECT value FROM app_meta WHERE key=?',key))?.value;
  const balance=async user=>Number((await f.one('SELECT coin FROM users WHERE id=?',user)).coin);
  const grantBody=async(userId,month)=>({userId,month,action:'GRANT',note:'격리 결제 확인',expectedRevision:(await info(userId)).subscription.revision,requestId:crypto.randomUUID()});
  const confirm=body=>f.call('admin/server-support',{body});
  const config=async(document,expectedRevision=0)=>f.call('admin/server-support/pass',{body:{month:2,document,expectedRevision,requestId:crypto.randomUUID()}});
  const secondDocument=f.document([{code:'COIN:',quantity:200}]);
  secondDocument.title='두 번째 달';
  const single=(user,month,pass,day=1)=>f.call('server-support/pass/claim',{user,body:{month,cycle:pass.cycle,day,expectedRevision:pass.revision}});
  const batch=(user,month,pass,id=crypto.randomUUID())=>f.call('server-support/pass/claim-all',{user,body:{...pass.claimAll,month,requestId:id}});
  const sale=f.clock.now;
  let oldReceipt,firstConfig,firstExpiry;

  await t.test('기존 등록과 영수증은 1개월차에 속하고 빈 2개월차는 판매할 수 없다',async()=>{
    await f.save(f.document([{code:'COIN:',quantity:7}]));
    // Simulate the production format with no per-month entitlement fields.
    const legacy={version:1,revision:3,startsAt:sale,endsAt:sale+30*DAY_MS,revokedAt:null,magnetPetCode:null};
    await f.run('INSERT INTO app_meta(key,value) VALUES(?,?)','server_support_v1:2',JSON.stringify(legacy));
    firstConfig=await raw(PASS_KEY);firstExpiry=legacy.endsAt;
    const first=(await info(2)).seasonPass;
    assert.equal((await single(2,undefined,first)).status,200);
    oldReceipt=await raw(claimKey(2,first.cycle,1));
    const before=await info(2);
    assert.equal(before.seasonPass.active,true);assert.equal(before.secondSeasonPass.purchased,false);
    assert.equal(before.secondSeasonPass.enabled,false);assert.equal(before.secondSeasonPass.days.length,30);
    assert.equal(await raw(passConfigKey(2)),undefined);assert.equal((await f.setting(true)).status,200);
    assert.equal((await f.issue(2,crypto.randomUUID(),{month:2})).status,409);
    assert.equal((await confirm(await grantBody(2,2))).status,409);
    const incomplete=structuredClone(secondDocument);incomplete.days[29].rewards=[];
    assert.equal((await config(incomplete)).status,400);
    assert.equal((await config({...incomplete,enabled:false})).status,200);
    assert.equal((await f.issue(2,crypto.randomUUID(),{month:2})).status,409);
    assert.equal(await raw(PASS_KEY),firstConfig);assert.equal(await balance(2),1241);
  });
  await t.test('2개월차 개방·신청만으로는 수령 불가, 승인 시 선택한 달만 부여',async()=>{
    assert.equal((await config(secondDocument,1)).status,200);
    const account=await info(2);
    assert.equal(account.secondSeasonPass.salesStartsAt,sale);
    assert.equal((await single(2,2,account.seasonPass)).status,403);
    assert.equal((await batch(2,2,account.seasonPass)).status,403);
    const requestId=crypto.randomUUID(),application=await f.issue(3,requestId,{month:2});
    assert.equal(application.status,200);assert.equal(application.body.month,2);
    assert.equal((await f.issue(3,requestId,{month:2})).body.replayed,true);
    assert.equal((await f.issue(3,requestId,{month:1})).status,409);
    assert.match((await f.messages(3)).body.messages[0].body,/2개월차 시즌패스/);
    const preview=(await f.call('admin/server-support/preview',{body:{recipientType:'ID',recipient:'3'}})).body;
    assert.equal(preview.lastPassApplication.month,2);assert.equal((await info(3)).secondSeasonPass.active,false);
    assert.equal((await f.grant(3)).status,409);
    const purchase=await grantBody(3,2);f.fail('INSERT INTO admin_logs');
    assert.equal((await confirm(purchase)).status,503);f.fail('');
    assert.equal((await info(3)).secondSeasonPass.purchased,false);
    assert.equal((await confirm(purchase)).status,200);assert.equal((await confirm(purchase)).body.replayed,true);
    assert.equal((await confirm({...purchase,month:1})).status,409);
    assert.equal((await confirm(await grantBody(3,2))).status,409);
    assert.equal((await f.issue(3,crypto.randomUUID(),{month:2})).status,409);
    const secondOnly=await info(3);
    assert.equal(secondOnly.seasonPass.purchased,false);assert.equal(secondOnly.secondSeasonPass.active,true);
    assert.equal((await single(3,1,secondOnly.secondSeasonPass)).status,403);
    assert.equal((await batch(3,1,secondOnly.secondSeasonPass)).status,403);
    assert.equal((await single(3,3,secondOnly.secondSeasonPass)).status,400);
    assert.equal((await single(3,2,secondOnly.secondSeasonPass)).status,200);
    assert.equal(await balance(3),1434);
  });
  await t.test('두 달을 사도 달력·만료·수령 영수증은 독립적이며 응답 복구 시 한 번만 지급',async()=>{
    f.clock.now+=2*DAY_MS;
    const purchase=await grantBody(2,2);assert.equal((await confirm(purchase)).status,200);
    const both=await info(2);
    assert.equal(both.seasonPass.claimedCount,1);assert.equal(both.secondSeasonPass.claimedCount,0);
    assert.equal(both.seasonPass.expiresAt,firstExpiry);assert.equal(both.secondSeasonPass.expiresAt,f.clock.now+30*DAY_MS);
    assert.equal(both.seasonPass.cycle,both.secondSeasonPass.cycle);
    assert.equal(both.secondSeasonPass.claimableCount,3);
    const requestId=crypto.randomUUID();f.fail('INSERT INTO coin_logs');
    assert.equal((await batch(2,2,both.secondSeasonPass,requestId)).status,503);f.fail('');
    assert.equal((await info(2)).secondSeasonPass.claimedCount,0);assert.equal(await balance(2),1241);
    const paid=await batch(2,2,both.secondSeasonPass,requestId);assert.equal(paid.status,200);assert.equal(paid.body.dayCount,3);
    assert.equal((await batch(2,2,both.secondSeasonPass,requestId)).body.replayed,true);
    assert.equal((await single(2,2,both.secondSeasonPass)).body.replayed,true);assert.equal(await balance(2),1841);
    assert.equal((await single(2,1,both.seasonPass)).body.rewards[0].quantity,7);
    assert.equal(await raw(claimKey(2,both.seasonPass.cycle,1)),oldReceipt);
    assert.equal((await batch(2,1,both.seasonPass)).body.dayCount,2);
    assert.equal((await config({...secondDocument,enabled:false},2)).status,200);
    f.clock.now+=DAY_MS;assert.equal((await config(secondDocument,3)).status,200);
    assert.equal((await info(2)).secondSeasonPass.salesStartsAt,sale);assert.equal(await raw(PASS_KEY),firstConfig);
    f.clock.now=firstExpiry;
    const expired=await info(2);assert.equal(expired.seasonPass.claimableCount,0);assert.equal(expired.secondSeasonPass.claimableCount,27);
    assert.equal((await single(2,1,expired.seasonPass,5)).status,403);
    assert.equal((await batch(2,2,expired.secondSeasonPass)).body.dayCount,27);
    assert.equal((await info(2)).secondSeasonPass.claimableCount,0);
    await f.grant(2,'REVOKE');const revoked=await info(2);assert.equal(revoked.secondSeasonPass.active,false);
    assert.equal((await batch(2,2,both.secondSeasonPass,requestId)).body.replayed,true);
    assert.equal((await f.grant()).status,200);assert.equal((await info(2)).secondSeasonPass.purchased,false);
  });
});
