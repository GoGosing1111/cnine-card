import assert from 'node:assert/strict';
import test from 'node:test';
import {passFixture} from './helpers/supporter-pass-fixture.mjs';
import {addApplicationFixture} from './helpers/supporter-application-fixture.mjs';

for(const postgres of [false,true])test((postgres?'PostgreSQL':'SQLite')+' 월별 구매 신청부터 입금 확인까지',async t=>{
  const f=await addApplicationFixture(await passFixture({postgres}),{postgres});t.after(()=>f.close());
  const request=(user=2,requestId=crypto.randomUUID())=>f.call('server-support/pass/purchase-request',{user,body:{requestId}});
  const alerts=(user=1)=>f.call('admin/server-support/package/alerts',{user});
  const info=async user=>(await f.call('server-support/info',{user})).body;
  const config=async enabled=>f.call('admin/server-support/pass',{body:{month:2,document:{...f.document(),enabled},expectedRevision:0,requestId:crypto.randomUUID()}});
  const grant=(userId,month,revision,extra={})=>({userId,month,expectedRevision:revision,action:'GRANT',requestId:crypto.randomUUID(),note:'격리 입금 대조',...extra});
  const confirm=body=>f.call('admin/server-support',{body});
  assert.equal((await request()).status,409);
  assert.equal((await config(true)).status,200);
  assert.equal((await info(2)).application.enabled,false);assert.equal((await info(2)).secondSeasonPass.canRequestPurchase,true);
  for(const id of [0,4,5,6])assert.ok([401,403,404].includes((await request(id)).status));
  assert.equal((await request(2,'x')).status,400);
  for(const id of [2,3])assert.equal((await alerts(id)).status,403);
  assert.deepEqual((await alerts()).body.passPending,[]);
  const requestId=crypto.randomUUID();
  f.fail('INSERT INTO app_meta(key,value) VALUES');assert.equal((await request(2,requestId)).status,503);f.fail('');
  assert.deepEqual((await alerts()).body.passPending,[]);
  const first=await request(2,requestId);assert.equal(first.status,200);
  const pending=first.body.pending;assert.equal(pending.userId,2);assert.equal(pending.id,'2_'+requestId);
  assert.deepEqual((await request(2,requestId)).body.pending,pending);
  assert.deepEqual((await request()).body.pending,pending);
  const snapshot=await info(2);assert.equal(snapshot.secondSeasonPass.purchasePending,true);assert.equal(snapshot.secondSeasonPass.active,false);
  assert.equal((await f.messages(2)).body.messages.length,0);
  const rows=(await alerts()).body.passPending;
  assert.deepEqual(rows.map(o=>[o.id,o.userId,o.month,o.priceWon]),[[pending.id,2,2,29800]]);
  assert.deepEqual((await f.call('admin/server-support')).body.passPending,rows);
  assert.equal((await confirm(grant(2,2,0,{passApplicationId:'2_expired'}))).status,409);
  assert.equal((await confirm(grant(3,2,0,{passApplicationId:pending.id}))).status,400);
  assert.equal((await f.setting(true)).status,200);
  assert.equal((await f.issue(3,crypto.randomUUID(),{month:1})).status,200);
  assert.equal((await alerts()).body.passPending.length,1);
  assert.equal((await f.issue(2,crypto.randomUUID(),{month:2})).status,200);
  assert.equal((await f.issue(3,crypto.randomUUID(),{month:2})).status,200);
  assert.deepEqual((await request(2)).body.pending,pending);assert.equal((await alerts()).body.passPending.length,2);
  assert.equal((await confirm(grant(2,1,0))).status,200);
  assert.equal((await info(2)).secondSeasonPass.purchasePending,true);
  const body=grant(2,2,1,{passApplicationId:pending.id});
  assert.equal((await confirm({...body,note:''})).status,400);
  f.fail('INSERT INTO admin_logs');assert.equal((await confirm(body)).status,503);f.fail('');
  assert.equal((await info(2)).secondSeasonPass.purchased,false);assert.equal((await alerts()).body.passPending.length,2);
  const approved=await confirm(body);assert.equal(approved.status,200);assert.equal(approved.body.passApplicationId,pending.id);
  assert.equal((await confirm(body)).body.replayed,true);
  assert.equal((await confirm({...body,passApplicationId:'2_changed'})).status,409);
  assert.deepEqual((await alerts()).body.passPending.map(o=>o.userId),[3]);assert.deepEqual((await alerts()).body.pending,[]);
  const after=await info(2);assert.equal(after.secondSeasonPass.active,true);assert.equal(after.secondSeasonPass.purchasePending,false);assert.equal(after.secondSeasonPass.canRequestPurchase,false);
  assert.equal(after.subscription.revision,2);assert.equal((await request(2,requestId)).body.purchased,true);
  const manual=await confirm(grant(3,2,0));assert.equal(manual.status,200);
  assert.deepEqual((await alerts()).body.passPending,[]);assert.equal((await info(3)).seasonPass.purchased,false);
});

