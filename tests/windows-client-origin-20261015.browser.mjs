import {createServer} from 'node:https';
import {mkdtemp,mkdir,readFile,writeFile} from 'node:fs/promises';
import {createHash,X509Certificate} from 'node:crypto';
import {spawnSync} from 'node:child_process';
import {pathToFileURL} from 'node:url';
import path from 'node:path';
import os from 'node:os';
import assert from 'node:assert/strict';
import {assertJointOrigin} from '../functions/_joint_request.js';
const {_electron}=await import(process.env.PLAYWRIGHT_MODULE||'playwright');
const [build,output]=process.argv.slice(2);
if(!build||!output)throw Error('Supply external build and QA output directories');
await mkdir(output,{recursive:true});
const temporary=await mkdtemp(path.join(os.tmpdir(),'soop-origin-'));
const certificate=path.join(temporary,'fixture.crt'),key=path.join(temporary,'fixture.key');
const openssl=process.env.OPENSSL_PATH||'C:/Program Files/Git/usr/bin/openssl.exe';
const generated=spawnSync(openssl,['req','-x509','-newkey','rsa:2048','-nodes','-keyout',key,'-out',certificate,'-days','1','-subj','/CN=cnine-card.pages.dev','-addext','subjectAltName=DNS:cnine-card.pages.dev,DNS:foreign.invalid'],{windowsHide:true,encoding:'utf8'});
assert.equal(generated.status,0,generated.stderr);
const cert=await readFile(certificate);
const spki=createHash('sha256').update(new X509Certificate(cert).publicKey.export({type:'spki',format:'der'})).digest('base64');
const origin='https://cnine-card.pages.dev',requests=[];
const server=createServer({cert,key:await readFile(key)},async(req,res)=>{
  const chunks=[];for await(const b of req)chunks.push(b);
  const headers=new Headers(req.headers);let error=null;
  try{assertJointOrigin(new Request(origin+req.url,{method:req.method,headers}));}catch(e){error=e.code;}
  const record={url:req.url,method:req.method,origin:headers.get('origin'),site:headers.get('sec-fetch-site'),cookie:headers.get('cookie'),authorization:headers.get('authorization'),body:Buffer.concat(chunks).toString(),error};
  requests.push(record);res.writeHead(error?403:200,{'content-type':'application/json'});res.end(JSON.stringify(record));
});
await new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const moduleUrl=pathToFileURL(path.resolve('packaging/windows-client/lib/network-request.mjs')).href;
const main=path.join(temporary,'main.mjs');
await writeFile(main,`import {app,BrowserWindow,session} from 'electron';
import {forwardNetworkRequest} from ${JSON.stringify(moduleUrl)};
app.setPath('userData',${JSON.stringify(path.join(temporary,'profile'))});
app.whenReady().then(async()=>{globalThis.legacy=true;globalThis.incoming=[];
const s=session.fromPartition('persist:qa-origin');
s.protocol.handle('https',async request=>{
  const u=new URL(request.url);
  if(u.pathname==='/')return new Response('<!doctype html><title>Native origin QA</title><body>Origin QA</body>',{headers:{'content-type':'text/html'}});
  globalThis.incoming.push({origin:request.headers.get('origin'),initiator:request.initiatorOrigin,credentials:request.credentials,referrer:request.referrer});
  return globalThis.legacy?s.fetch(request,{bypassCustomProtocolHandlers:true}):forwardNetworkRequest(s,request);
});
const win=new BrowserWindow({show:false,webPreferences:{session:s,nodeIntegration:false,sandbox:true,contextIsolation:true,webSecurity:true}});
await win.loadURL(${JSON.stringify(origin+'/')});
});
app.on('window-all-closed',()=>app.quit());
`);
const electron=await _electron.launch({executablePath:path.join(build,'node_modules/electron/dist/electron.exe'),args:[main,`--host-resolver-rules=MAP cnine-card.pages.dev 127.0.0.1:${server.address().port},MAP foreign.invalid 127.0.0.1:${server.address().port}`,'--no-proxy-server',`--ignore-certificate-errors-spki-list=${spki}`],timeout:30000});
try{
  const page=await electron.firstWindow();
  await page.evaluate(()=>{document.cookie='qa-session=kept; Secure; SameSite=Lax';});
  const post=()=>page.evaluate(async()=>{const response=await fetch('/api/scrapyard/v3/run',{method:'POST',headers:{'content-type':'application/json',authorization:'Bearer isolated-qa'},body:JSON.stringify({requestId:'isolated-no-production-write',difficultyId:1})});return {status:response.status,body:await response.json()};});
  const before=await post();assert.equal(before.status,403);assert.equal(before.body.origin,null);assert.equal(before.body.error,'JOINT_ORIGIN');
  await electron.evaluate(()=>{globalThis.legacy=false;});
  const after=await post();console.log(JSON.stringify({before,after,incoming:await electron.evaluate(()=>globalThis.incoming)},null,2));
  assert.equal(after.status,200);assert.equal(after.body.origin,origin);assert.equal(after.body.site,'same-origin');assert.equal(after.body.error,null);
  assert.equal(after.body.authorization,'Bearer isolated-qa');assert.deepEqual(JSON.parse(after.body.body),{requestId:'isolated-no-production-write',difficultyId:1});
  assert.match(after.body.cookie||'',/qa-session=kept/);
  const noReferrer=await page.evaluate(async()=>{const r=await fetch('/api/scrapyard/v3/run?no-referrer',{method:'POST',referrerPolicy:'no-referrer',body:'qa'});return {status:r.status,body:await r.json()};});
  assert.equal(noReferrer.status,200,'trusted native initiator works even without a Referer');
  const foreign=await electron.evaluate(async({BrowserWindow,session})=>{const w=new BrowserWindow({show:false,webPreferences:{session:session.fromPartition('persist:qa-origin'),sandbox:true,contextIsolation:true,webSecurity:true}});await w.loadURL('https://foreign.invalid/');return w.id;});
  const foreignPage=electron.windows().find(p=>p.url().startsWith('https://foreign.invalid'));
  await foreignPage.evaluate(async target=>{try{await fetch(target+'/api/scrapyard/v3/run?foreign',{method:'POST',body:'qa'});}catch{}},origin);
  const foreignRequests=requests.filter(r=>r.url.includes('?foreign'));
  assert(foreignRequests.length);assert(foreignRequests.every(r=>r.error==='JOINT_ORIGIN'&&r.origin!==origin));
  await page.evaluate(async target=>{const frame=document.createElement('iframe');frame.sandbox='allow-scripts';frame.srcdoc='<script>fetch('+JSON.stringify(target+'/api/scrapyard/v3/run?opaque')+', {method:"POST",body:"qa"}).catch(()=>{});<\/script>';document.body.append(frame);},origin);
  for(let i=0;i<50&&!requests.some(r=>r.url.includes('?opaque'));i++)await new Promise(r=>setTimeout(r,100));
  const opaqueRequests=requests.filter(r=>r.url.includes('?opaque'));assert(opaqueRequests.length);assert(opaqueRequests.every(r=>r.error==='JOINT_ORIGIN'&&r.origin!==origin));
  const report={passed:true,transport:'native HTTPS using a temporary pinned local TLS certificate',productionRequests:0,before,after,noReferrer:noReferrer.status,foreignRejected:foreignRequests.length,opaqueRejected:opaqueRequests.length};
  await writeFile(path.join(output,'report.json'),JSON.stringify(report,null,2)+'\n');console.log('Native HTTPS scrapyard Origin regression PASS');
}finally{await electron.close();server.closeAllConnections();await new Promise(resolve=>server.close(resolve));}
