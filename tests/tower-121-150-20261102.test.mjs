test('local PostgreSQL activation is atomic, append-only, protected by hashes, and replay performs zero writes',async t=>{
 const f=await operationFixture(t),canaries=await f.canaries();
 await assert.rejects(()=>applyTowerExpansion(f.db,{...f.proof,dryRun:false}),/authorization/);
 await assert.rejects(()=>applyTowerExpansion(f.db,{...f.proof,dryRun:false,authorization:OP}),/two-mercenary/);
 await assert.rejects(()=>applyTowerExpansion(f.db,{...f.proof,expectedHash:'f'.repeat(64)}),/changed after review/);
 await assert.rejects(()=>applyTowerExpansion(f.db,{...f.proof,expectedPlanHash:'f'.repeat(64)}),/plan changed/);
 const rehearsal=await applyTowerExpansion(f.db,f.proof);assert.equal(rehearsal.dryRun,true);
 assert.equal((await inspectTowerExpansion(f.db)).sourceHash,f.before.sourceHash);
 for(const failure of ['INSERT INTO tower_floor_ranges','UPDATE tower_seasons','INSERT INTO admin_logs','INSERT INTO app_meta']){
  f.fail(failure);await assert.rejects(()=>applyTowerExpansion(f.db,f.proof),/INJECTED/);f.fail('');
  assert.equal((await inspectTowerExpansion(f.db)).sourceHash,f.before.sourceHash);assert.deepEqual(await f.canaries(),canaries);
 }
 const done=await applyTowerExpansion(f.db,{...f.proof,dryRun:false,authorization:OP,dualMercenariesReleased:true});
 assert.equal(done.receipt.addedFloors,30);assert.deepEqual(await f.canaries(),canaries);
 assert.equal((await f.pg.query('SELECT COUNT(*) n FROM admin_logs')).rows[0].n,1);
 // Subsequent operator edits must survive a repeat execution of this operation.
 await f.pg.query('UPDATE tower_floor_ranges SET reward_coin=42 WHERE start_floor=150');
 f.calls.length=0;assert.equal((await applyTowerExpansion(f.db,f.proof)).replayed,true);
 assert(f.calls.every(sql=>sql.startsWith('SELECT')));assert.equal((await f.pg.query('SELECT reward_coin FROM tower_floor_ranges WHERE start_floor=150')).rows[0].reward_coin,42);
});

