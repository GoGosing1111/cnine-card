import test from 'node:test';
import assert from 'node:assert/strict';
import {PGlite} from '@electric-sql/pglite';
import {grantJinmu,inspectJinmuGrant,verifyJinmuGrant} from '../scripts/ops/heeya-jinmu-grant-20261015.mjs';

test('one authorized Jinmu grant: rollback, failed writes, receipt replay, identity and existing-copy preservation',async t=>{
 const db=new PGlite();t.after(()=>db.close());
 await db.exec(`CREATE TABLE users(id bigint primary key,nickname text,role text,status text,coin bigint,card_shards bigint,magic_crystals bigint);
 CREATE TABLE user_second_verifications(user_id bigint primary key,provider text,provider_user_id text);
 CREATE TABLE app_meta(key text primary key,value text,updated_at text);
 CREATE TABLE user_mercenary_cards_v1(user_id bigint,mercenary_code text,total_copies int,duplicate_count int,first_obtained_at text,last_obtained_at text,primary key(user_id,mercenary_code));
 CREATE TABLE mercenary_card_acquisitions_v1(acquisition_id text primary key,user_id bigint,mercenary_code text,is_duplicate int,total_copies_after int,duplicate_count_after int,created_at text);
 CREATE TABLE mercenary_limited_stock_v1(code text primary key,issued int,stock_limit int);
 CREATE TABLE mercenary_limited_issues_v1(code text,serial int);
 CREATE TABLE admin_logs(id bigint generated by default as identity primary key,admin_id bigint,action_type text,target_type text,target_id text,before_data text,after_data text);
 CREATE TABLE cnine_user_inventory(user_id bigint,item_code text,quantity int);
 CREATE TABLE user_mercenary_loadout_v1(user_id bigint,mercenary_code text);
 CREATE TABLE user_mercenary_growth_v1(user_id bigint,mercenary_code text,level int);
 INSERT INTO users VALUES(4977,'하이희야♡','USER','ACTIVE',9000,3,4);
 INSERT INTO user_second_verifications VALUES(4977,'PLAYDK','5e2dc209');
 INSERT INTO app_meta VALUES('mercenary_limited_pack_v1','{"mode":"OFF"}',null);
 INSERT INTO app_meta VALUES('mercenary_pvp_loadout_v1:4977','{"mercenaryCode":"V-999","revision":2}','old');
 INSERT INTO users VALUES(1,'핑크빛유두','OWNER','ACTIVE',7000,1,1),(4824,'헬로희야','USER','ACTIVE',3000,1,1);
 INSERT INTO user_mercenary_cards_v1 VALUES(1,'V-989',1,0,'old','old');
 INSERT INTO cnine_user_inventory VALUES(4977,'MASTER_STAR',100);
 INSERT INTO user_mercenary_loadout_v1 VALUES(4977,'V-999');
 INSERT INTO user_mercenary_cards_v1 VALUES(4977,'V-999',1,0,'old','old');`);
 const snapshot=async()=>{const rows={};for(const table of ['users','user_mercenary_cards_v1','mercenary_card_acquisitions_v1','mercenary_limited_stock_v1','mercenary_limited_issues_v1','app_meta','admin_logs','user_mercenary_loadout_v1','cnine_user_inventory'])rows[table]=(await db.query('SELECT * FROM '+table+' ORDER BY 1')).rows;return rows;};
 const untouched=await snapshot();
 const lease=()=>({lockDeadline:Date.now()+120000}),original=await inspectJinmuGrant(db);
 await assert.rejects(grantJinmu(db),/lease/);
 assert.equal((await grantJinmu(db,{...lease(),dryRun:true})).receipt.copiesAfter,1);
 assert.deepEqual(await inspectJinmuGrant(db),original);assert.deepEqual(await snapshot(),untouched);
 for(const table of ['user_mercenary_cards_v1','mercenary_card_acquisitions_v1','admin_logs','app_meta']){
  const failed={query:async(sql,args)=>{if(sql.startsWith('INSERT INTO '+table+'('))throw Error('INJECTED_FAILURE');return db.query(sql,args);}};
  await assert.rejects(grantJinmu(failed,lease()),/INJECTED_FAILURE/);assert.deepEqual(await inspectJinmuGrant(db),original);
  assert.equal((await db.query('SELECT * FROM mercenary_card_acquisitions_v1')).rows.length,0);
  assert.equal((await db.query('SELECT * FROM admin_logs')).rows.length,0);
 }
 await db.query("UPDATE users SET nickname='different' WHERE id=4977");await assert.rejects(grantJinmu(db,lease()));
 await db.query("UPDATE users SET nickname='하이희야♡' WHERE id=4977");
 await db.query("UPDATE user_second_verifications SET provider_user_id='wrong' WHERE user_id=4977");await assert.rejects(grantJinmu(db,lease()));
 await db.query("UPDATE user_second_verifications SET provider_user_id='5e2dc209' WHERE user_id=4977");
 await db.query("INSERT INTO user_mercenary_cards_v1 VALUES(4977,'V-989',2,1,'first','last')");
 const first=await grantJinmu(db,lease()),replay=await grantJinmu(db,lease());
 assert.equal(first.replayed,false);assert.equal(first.receipt.copiesBefore,2);assert.equal(first.receipt.copiesAfter,3);
 assert.equal(replay.replayed,true);assert.equal(replay.currentCopies,3);assert.equal((await verifyJinmuGrant(db)).missing,0);
 assert.equal((await db.query('SELECT * FROM mercenary_card_acquisitions_v1')).rows.length,1);
 assert.equal((await db.query('SELECT * FROM admin_logs')).rows.length,1);
 assert.equal((await db.query("SELECT first_obtained_at FROM user_mercenary_cards_v1 WHERE user_id=4977 AND mercenary_code='V-989'")).rows[0].first_obtained_at,'first');
 assert.equal((await db.query('SELECT coin FROM users WHERE id=4977')).rows[0].coin,9000);
 assert.equal((await db.query("SELECT total_copies FROM user_mercenary_cards_v1 WHERE user_id=1 AND mercenary_code='V-989'")).rows[0].total_copies,1);
 assert.equal((await db.query('SELECT * FROM user_mercenary_cards_v1 WHERE user_id=4824')).rows.length,0);
 assert.equal((await db.query('SELECT * FROM mercenary_limited_stock_v1')).rows.length,0);
 assert.equal((await db.query('SELECT * FROM mercenary_limited_issues_v1')).rows.length,0);
 assert.equal((await db.query('SELECT mercenary_code FROM user_mercenary_loadout_v1 WHERE user_id=4977')).rows[0].mercenary_code,'V-999');
});
