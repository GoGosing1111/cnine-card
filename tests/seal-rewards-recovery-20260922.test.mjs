import test from 'node:test';
import assert from 'node:assert/strict';
import {PGlite} from '@electric-sql/pglite';
import {recoverSeal46,SEAL_RECOVERY_KEY,SEAL_RECOVERY_EVENT_KEY} from '../scripts/ops/seal-rewards-20260922.mjs';

test('46회차 보상: 10회 경계·기존 순위·전액 지급·부분 실패 롤백·기지급 제외·재실행',async t=>{
  const db=new PGlite();t.after(()=>db.close());
  await db.exec(`CREATE FUNCTION sqlite_now() RETURNS TEXT LANGUAGE SQL STABLE AS $$ SELECT to_char(timezone('UTC',CURRENT_TIMESTAMP),'YYYY-MM-DD HH24:MI:SS') $$;
    CREATE TABLE app_meta(key TEXT PRIMARY KEY,value TEXT,updated_at TEXT);
    CREATE TABLE users(id BIGINT PRIMARY KEY,nickname TEXT,role TEXT,coin BIGINT DEFAULT 1000,card_shards BIGINT DEFAULT 7);
    CREATE TABLE seal_battle_events(id BIGINT PRIMARY KEY,event_key TEXT,status TEXT,min_reward_attempts BIGINT,clear_coin BIGINT,clear_shards BIGINT,rank_rewards_json TEXT,updated_at TEXT);
    CREATE TABLE seal_battle_user_progress(event_id BIGINT,user_id BIGINT,total_attempts BIGINT,total_contribution BIGINT,last_contribution_at TEXT);
    CREATE TABLE seal_battle_clear_claims(event_id BIGINT,user_id BIGINT,status TEXT,reward_coin BIGINT,reward_shards BIGINT,claimed_at TEXT,updated_at TEXT,PRIMARY KEY(event_id,user_id));
    CREATE TABLE seal_battle_rank_claims(event_id BIGINT,user_id BIGINT,final_rank BIGINT,total_contribution BIGINT,reward_json TEXT,status TEXT,claimed_at TEXT,created_at TEXT,updated_at TEXT,PRIMARY KEY(event_id,user_id));
    CREATE TABLE coin_logs(user_id BIGINT,change_amount BIGINT,balance_after BIGINT,reason TEXT);
    CREATE TABLE cnine_user_inventory(user_id BIGINT,item_code TEXT,quantity BIGINT,unseen_quantity BIGINT,created_at TEXT,updated_at TEXT,PRIMARY KEY(user_id,item_code));
    CREATE TABLE inventory_logs(id BIGINT GENERATED BY DEFAULT AS IDENTITY,user_id BIGINT,item_code TEXT,change_amount BIGINT,balance_after BIGINT,reason TEXT,reference_type TEXT,reference_id TEXT);
    CREATE TABLE admin_logs(id BIGINT GENERATED BY DEFAULT AS IDENTITY,admin_id BIGINT,action_type TEXT,target_type TEXT,target_id TEXT,before_data TEXT,after_data TEXT);
    INSERT INTO users(id,nickname,role) VALUES(1,'핑크빛유두','OWNER');
    INSERT INTO users(id,nickname,role) SELECT n,'테스트 '||n,'USER' FROM generate_series(2,174) n;
    INSERT INTO seal_battle_user_progress SELECT 46,n,CASE WHEN n<=124 THEN 10 ELSE 9 END,1000000-n,'2026-09-22 12:00:00' FROM generate_series(2,174) n;
    INSERT INTO app_meta VALUES('seal_battle_settings_v1','{"minRewardAttempts":20}',NULL);`);
  const tiers=[{startRank:1,endRank:1,coin:100000,premiumCube:1,equipmentBox:30},{startRank:2,endRank:3,coin:90000,premiumCube:1,equipmentBox:15},{startRank:6,endRank:10,coin:50000,premiumCube:1,equipmentBox:3}];
  await db.query("INSERT INTO seal_battle_events VALUES(46,$1,'CLEARED',30,5000000000,0,$2,NULL)",[SEAL_RECOVERY_EVENT_KEY,JSON.stringify({enabled:true,tiers})]);
  const q=async(sql,values=[])=>(await db.query(sql,values)).rows;
  const scalar=async sql=>Number((await q(sql))[0].n);
  await db.exec('BEGIN');
  await assert.rejects(recoverSeal46(async(sql,values)=>{if(sql.includes('WITH awarded AS'))throw Error('INJECTED_FAILURE');return q(sql,values)}),/INJECTED_FAILURE/);
  await db.exec('ROLLBACK');
  assert.equal(await scalar('SELECT COUNT(*) n FROM seal_battle_clear_claims'),0);
  assert.equal(await scalar('SELECT COUNT(*) n FROM coin_logs'),0);
  assert.equal(await scalar('SELECT coin n FROM users WHERE id=2'),1000);
  assert.equal(await scalar('SELECT min_reward_attempts n FROM seal_battle_events WHERE id=46'),30);
  await db.exec('BEGIN');
  const first=await recoverSeal46(q);
  assert.equal(first.clearPaidUsers,123);assert.equal(first.rankPaidUsers,8);
  assert.equal(first.clearCoin,615000000000);assert.equal(first.rankCoin,530000);
  assert.equal(first.premiumCubes,8);assert.equal(first.equipmentBoxes,75);
  assert.equal(await scalar('SELECT coin n FROM users WHERE id=124'),5000001000,'exactly 10 gets paid');
  assert.equal(await scalar('SELECT coin n FROM users WHERE id=125'),1000,'9 gets no reward');
  assert.equal(await scalar('SELECT COUNT(*) n FROM seal_battle_rank_claims WHERE final_rank IN (4,5)'),0,'unconfigured rank gaps preserved');
  assert.equal((await recoverSeal46(q)).replayed,true);
  assert.equal(await scalar('SELECT COUNT(*) n FROM coin_logs'),131);
  assert.equal(await scalar('SELECT COUNT(*) n FROM admin_logs'),1);
  assert.equal((await q("SELECT value FROM app_meta WHERE key='seal_battle_settings_v1'"))[0].value,'{"minRewardAttempts":20}');
  await db.exec('ROLLBACK');
  // An already-paid participant keeps their existing receipt and balance.
  await db.exec("INSERT INTO seal_battle_clear_claims(event_id,user_id,status,reward_coin,reward_shards) VALUES(46,2,'COMPLETED',5000000000,0)");
  await db.exec('BEGIN');
  const second=await recoverSeal46(q);assert.equal(second.clearPaidUsers,122);
  assert.equal(await scalar('SELECT coin n FROM users WHERE id=2'),101000,'only unpaid rank reward credited');
  assert.equal(await scalar('SELECT COUNT(*) n FROM seal_battle_clear_claims'),123);
  await db.exec('ROLLBACK');
  await db.exec("UPDATE seal_battle_clear_claims SET status='CLAIMING' WHERE user_id=2;BEGIN");
  await assert.rejects(recoverSeal46(q),/in progress/);await db.exec('ROLLBACK');
  assert.equal((await q('SELECT value FROM app_meta WHERE key=$1',[SEAL_RECOVERY_KEY])).length,0);
});
