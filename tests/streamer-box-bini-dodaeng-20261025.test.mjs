async function transaction(db,{dryRun=false,failAt,overrides={}}={}){
 await db.query('BEGIN');try{
  const client={query:(sql,args)=>{if(failAt?.test(sql))throw Error('INJECTED_FAILURE');return db.query(sql,args);}};
  const result=await ops.grant(client,{...options(),...overrides});await db.query(dryRun?'ROLLBACK':'COMMIT');return result;
 }catch(e){await db.query('ROLLBACK');throw e;}
}
async function snapshot(db){const out={};for(const table of ['users','user_second_verifications','inventory_items','cnine_user_inventory','inventory_logs','admin_logs','app_meta'])out[table]=(await db.query('SELECT * FROM '+table+' ORDER BY 1,2')).rows;return out;}

test('transfer subtracts two from Bini and adds two to Dodaeng; original grant, wallets and other inventories stay unchanged; replay never restores opened boxes',async()=>{
 const db=await fixture();try{
  const before=await snapshot(db),dry=await transaction(db,{dryRun:true});assert.equal(dry.verification.netChange,0);assert.deepEqual(await snapshot(db),before);
  const result=await transaction(db),after=await snapshot(db);assert.equal(after.inventory_logs.length,2);assert.equal(after.admin_logs.length,1);assert.equal(after.app_meta.length,2);
  const from=result.receipt.allocations.find(a=>a.userId===ops.FROM_ID),to=result.receipt.allocations.find(a=>a.userId===ops.TO_ID);
  assert.deepEqual(from.after,{quantity:'0',unseen:'0'});assert.deepEqual(to.after,{quantity:'7',unseen:'4'});
  assert.deepEqual(after.inventory_logs.map(l=>[String(l.user_id),Number(l.change_amount)]).sort(),[[ops.TO_ID,2],[ops.FROM_ID,-2]].sort());
  for(const table of ['users','user_second_verifications','inventory_items'])assert.deepEqual(after[table],before[table]);
  const unrelated=r=>r.item_code!==gift.code||Number(r.user_id)===4852;assert.deepEqual(after.cnine_user_inventory.filter(unrelated),before.cnine_user_inventory.filter(unrelated));
  assert.deepEqual(after.app_meta.find(r=>r.key===ops.ORIGINAL_GRANT_KEY),before.app_meta[0]);
  const noWrites={query:(sql,args)=>{assert(/^SELECT/i.test(sql));return db.query(sql,args);}};
  assert.equal((await ops.grant(noWrites,{expectedPlanHash:ops.PLAN_HASH})).replayed,true);assert.deepEqual(await snapshot(db),after);
  await db.query('UPDATE cnine_user_inventory SET quantity=quantity-1 WHERE user_id=$1 AND item_code=$2',[ops.TO_ID,gift.code]);
  const spent=await snapshot(db);assert.equal((await ops.grant(noWrites,{expectedPlanHash:ops.PLAN_HASH})).replayed,true);assert.deepEqual(await snapshot(db),spent);
 }finally{await db.close();}
});
