const emptyArtifacts={receipt:null,coins:[],items:[],pig:[],audit:[]};
test('atomic grant adds 3000 pig coins and four BOGO packages, preserving ordinary coins, auction reservations and other holdings',async()=>{
 const {db,options}=await fixture();try{
  const before=await snapshot(db);await db.exec('BEGIN');const result=await grant(db,options);await db.exec('COMMIT');
  assert.equal(result.receipt.pig.after,'3460');assert.equal(result.receipt.coin.after,'800000000001000');
  assert.deepEqual(result.receipt.items.map(i=>[i.code,i.after]),[['EMPEROR_ENERGY','6041'],['MERCENARY_SSS_LIMITED_SHARD','45']]);
  assert.equal(result.receipt.availableBefore,'900');assert.deepEqual(result.receipt.accountingAfter.auctionReserved,{'123':50});
  assert.deepEqual(protectedState(await snapshot(db)),protectedState(before));await verify(db,undefined,{exact:true});
  assert.equal((await db.query("SELECT value FROM app_meta WHERE key='support_package_pending_v1:4981'")).rows[0].value,'4981_new');
  const replay=await grant({query:(sql,args)=>{assert.match(sql,/^SELECT\b/);return db.query(sql,args);}});assert(replay.replayed);assert.deepEqual(replay.receipt,result.receipt);
 }finally{await db.close();}
});
