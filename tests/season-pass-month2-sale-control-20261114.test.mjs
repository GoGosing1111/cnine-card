import test from 'node:test';
import assert from 'node:assert/strict';
import {passFixture} from './helpers/supporter-pass-fixture.mjs';
import {addApplicationFixture} from './helpers/supporter-application-fixture.mjs';

for (const postgres of [false,true]) test((postgres?'PostgreSQL':'SQLite')+' month-two purchase switch covers all issuance routes and preserves earned rewards',async t=>{
  const f=await addApplicationFixture(await passFixture({postgres}),{postgres});
  t.after(()=>f.close());
  const uuid=()=>crypto.randomUUID();
  const settings=(body,user=1)=>f.call('admin/server-support/application',{user,body});
  const info=async user=>(await f.call('server-support/info',{user})).body;
  const request=(user,id=uuid())=>f.call('server-support/pass/purchase-request',{user,body:{requestId:id}});
  const pay=(userId,extra={})=>({userId,month:2,action:'GRANT',note:'결제 확인',expectedRevision:0,requestId:uuid(),...extra});
  const approve=body=>f.call('admin/server-support',{body});
  const doc=f.document([{code:'COIN:',quantity:7}]);
  await f.save(doc);
  assert.equal((await f.call('admin/server-support/pass',{body:{month:2,document:doc,expectedRevision:0,requestId:uuid()}})).status,200);
  const legacy=await f.setting(true);
  assert.equal(legacy.body.config.secondMonthSalesOpen,true);
  const paid=pay(2);
  assert.equal((await approve(paid)).status,200);
  const bankId=uuid(),pending=await f.issue(3,bankId,{month:2});
  assert.equal(pending.status,200);
  const queued=pay(3,{passApplicationId:'3_'+bankId});
  const until=(await info(2)).secondSeasonPass.expiresAt;
  const stop={enabled:true,secondMonthSalesOpen:false,expectedRevision:1,requestId:uuid()};
  assert.equal((await settings(stop,3)).status,403);
  assert.equal((await settings({...stop,secondMonthSalesOpen:'OFF'})).status,400);
  assert.equal((await settings(stop)).body.config.secondMonthSalesOpen,false);
  assert.equal((await settings(stop)).body.replayed,true);
  assert.equal((await settings({...stop,secondMonthSalesOpen:true})).status,409);
  assert.equal((await settings({...stop,firstMonthSalesOpen:false,secondMonthSalesOpen:undefined})).status,409);
  const state=await info(3);
  assert.equal(state.seasonPass.saleClosed,false);
  assert.equal(state.secondSeasonPass.saleClosed,true);
  assert.equal(state.secondSeasonPass.purchasePending,true);
  assert.equal(state.secondSeasonPass.canRequestPurchase,false);
  assert.equal((await f.call('admin/server-support/preview',{body:{recipientType:'ID',recipient:'3'}})).body.secondMonthSalesOpen,false);
  const counts=async()=>Promise.all(['user_messages','app_meta','admin_logs'].map(async table=>Number((await f.one('SELECT count(*) n FROM '+table)).n)));
  const snapshot=await counts();
  for(const answer of [await f.issue(3,uuid(),{month:2}),await request(3),await request(1),await approve(queued),await approve(pay(1))]){
    assert.equal(answer.status,409,JSON.stringify(answer.body));
    assert.equal(answer.body.code,'SUPPORT_APPLICATION_MONTH2_CLOSED');
  }
  assert.equal((await f.issue(3,bankId,{month:2})).body.replayed,true);
  assert.equal((await request(3,bankId)).body.pending.id,queued.passApplicationId);
  assert.equal((await approve(paid)).body.replayed,true);
  assert.deepEqual(await counts(),snapshot);
  const buyer=await info(2);
  assert.equal(buyer.secondSeasonPass.expiresAt,until);
  assert.equal(buyer.secondSeasonPass.active,true);
  assert(buyer.secondSeasonPass.claimableCount>0);
  assert.equal((await f.call('server-support/pass/claim-all',{user:2,body:{...buyer.secondSeasonPass.claimAll,requestId:uuid()}})).status,200);
  assert.equal((await f.issue(3)).status,200);
  assert.equal((await f.setting(false,2)).body.config.secondMonthSalesOpen,false);
  assert.equal((await request(1)).body.code,'SUPPORT_APPLICATION_MONTH2_CLOSED');
  const open={enabled:false,secondMonthSalesOpen:true,expectedRevision:3,requestId:uuid()};
  assert.equal((await settings(open)).body.config.secondMonthSalesOpen,true);
  assert.equal((await f.issue(1,uuid(),{month:2})).body.code,'SUPPORT_APPLICATION_DISABLED');
  assert.equal((await request(1)).status,200);
  assert.equal((await approve(queued)).status,200);
  assert.equal((await info(3)).secondSeasonPass.active,true);
});
