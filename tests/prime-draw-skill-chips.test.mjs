for(const dialect of ['sqlite','postgres']){
  test(`${dialect}: CMS exposes the three chip candidates without assigning rewards or changing probabilities`,async t=>{
    const f=await fixture(t,dialect),before=await f.q('SELECT * FROM prime_equipment_draw_pool_v1985');
    const {body,status}=await f.call('admin/prime-draw/status');assert.equal(status,200);
    const chips=body.catalog.inventory_item.filter(row=>row.category==='SKILL_CHIP');
    assert.deepEqual(chips.map(row=>[row.code,row.name,row.rewardType]),[[ROCKET,'로켓런처 스킬칩','INVENTORY_ITEM'],[HELI,'헬기폭격 스킬칩','INVENTORY_ITEM'],[OCTA,'8방향 유도탄 스킬칩','INVENTORY_ITEM']]);
    assert.ok(chips.every(row=>row.image.endsWith('.webp')));
    assert.equal(body.catalog.inventory_item.filter(row=>row.category==='MATERIAL').length,6);
    assert.deepEqual(body.equipment.pool.entries.map(row=>[row.code,row.drawWeight]),[['EQUIP_1',100]]);
    assert.deepEqual(await f.q('SELECT * FROM prime_equipment_draw_pool_v1985'),before);
    assert.deepEqual(await f.q('SELECT * FROM prime_draw_extra_pool_v1987'),[]);
    assert.equal(await f.quantity(ROCKET),0);assert.equal(await f.quantity(HELI),0);assert.equal(await f.quantity(OCTA),0);
    await f.call('admin/prime-draw/status');
    assert.deepEqual(await f.q('SELECT * FROM prime_draw_extra_pool_v1987'),[]);
  });

  test(`${dialect}: manual chip probabilities persist, fresh opens grant stackable chips once and they can be equipped`,async t=>{
    const f=await fixture(t,dialect);
    const saved=await f.save({[ROCKET]:40,[HELI]:60});assert.equal(saved.status,200);
    assert.deepEqual(saved.body.pool.entries.filter(row=>row.category==='SKILL_CHIP').map(row=>[row.code,row.drawWeight]),[[HELI,60],[ROCKET,40]]);
    const publicConfig=await f.call('equipment/prime-supply-box/config');
    assert.equal(publicConfig.body.pool.entries.length,2);
    for(const [index,code] of [ROCKET,HELI].entries()){
      assert.equal((await f.save({[code]:100})).status,200);
      const opened=await f.open('chip-'+code,3);assert.equal(opened.status,200);
      assert.equal(opened.body.remainingQuantity,12-(index+1)*3);
      assert.ok(opened.body.results.every(row=>row.type==='INVENTORY_ITEM'&&row.item.code===code&&row.item.category==='SKILL_CHIP'));
      assert.deepEqual(opened.body.aggregated.map(row=>[row.code,row.count,row.category]),[[code,3,'SKILL_CHIP']]);
      assert.equal(await f.quantity(code),3);
      assert.equal((await f.q('SELECT unseen_quantity FROM cnine_user_inventory WHERE user_id=7 AND item_code=?',code))[0].unseen_quantity,3);
      assert.deepEqual(await f.open('chip-'+code,3),opened,'same receipt must replay without granting twice');
      assert.equal(await f.quantity(code),3);
      const equipped=await handleSkillChips({path:'character/skill-chips/equip',env:f.env,deps:f.deps,request:new Request('https://test.invalid/equip',{method:'POST',body:JSON.stringify({slot:index+1,code})})});
      assert.equal(equipped.status,200);assert.equal(equipped.body.skillChips.loadout[index],code);assert.equal(await f.quantity(code),3);
    }
    assert.equal((await f.open('stack-chip',2)).status,200);assert.equal(await f.quantity(HELI),5);
    assert.equal(await f.quantity(BOX),4);assert.equal(await f.quantity('EQUIPMENT_SUPPLY_BOX'),25);
    assert.deepEqual(await f.q('SELECT * FROM user_equipment_instances'),[]);
    assert.deepEqual(await f.q('SELECT * FROM avatar_user_ownership_v1'),[]);
    assert.equal((await f.q("SELECT COUNT(*) n FROM inventory_logs WHERE reason='PRIME_EQUIPMENT_REWARD'"))[0].n,3);
    assert.equal((await f.q('SELECT coin FROM users WHERE id=7'))[0].coin,1234567);
    assert.equal((await f.open('too-many',5)).status,409);assert.equal(await f.quantity(BOX),4);
  });

  test(`${dialect}: inactive, unapproved and vehicle chip assignments are rejected without mutating the pool`,async t=>{
    const f=await fixture(t,dialect);
    const before=await f.q('SELECT * FROM prime_equipment_draw_pool_v1985');
    assert.equal((await f.save({[ROCKET]:10},'equipment','USER')).status,403);
    assert.equal((await f.save({[ROCKET]:10},'vehicle')).status,409);
    await f.exec("INSERT INTO inventory_items(code,name,category) VALUES('UNAPPROVED_CHIP','unapproved','SKILL_CHIP')");
    assert.equal((await f.save({UNAPPROVED_CHIP:10})).status,409);
    await f.db.prepare('UPDATE inventory_items SET is_active=0 WHERE code=?').bind(ROCKET).run();
    assert.equal((await f.save({[ROCKET]:10})).status,409);
    assert.deepEqual(await f.q('SELECT * FROM prime_equipment_draw_pool_v1985'),before);
    assert.deepEqual(await f.q('SELECT * FROM prime_draw_extra_pool_v1987'),[]);
    const status=await f.call('admin/prime-draw/status');
    assert.deepEqual(status.body.catalog.inventory_item.filter(row=>row.category==='SKILL_CHIP').map(row=>row.code),[HELI,OCTA]);
    assert.equal((await f.save({[HELI]:100})).status,200);
    await f.db.prepare('UPDATE inventory_items SET is_active=0 WHERE code=?').bind(HELI).run();
    assert.equal((await f.open('inactive-chip')).status,503);assert.equal(await f.quantity(BOX),12);
  });

  test(`${dialect}: a suppressed box debit cannot grant free chips or complete a receipt`,async t=>{
    const f=await fixture(t,dialect);await f.save({[HELI]:100});
    if(f.pg)await f.exec(`CREATE FUNCTION suppress_box_debit() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.item_code='${BOX}' THEN RETURN NULL; END IF; RETURN NEW; END $$;
      CREATE TRIGGER suppress_box_debit BEFORE UPDATE ON cnine_user_inventory FOR EACH ROW EXECUTE FUNCTION suppress_box_debit();`);
    else await f.exec(`CREATE TRIGGER suppress_box_debit BEFORE UPDATE ON cnine_user_inventory WHEN NEW.item_code='${BOX}' BEGIN SELECT RAISE(IGNORE); END;`);
    await assert.rejects(()=>f.open('box-debit-failed',2),/not.null|null value/i);
    assert.equal(await f.quantity(BOX),12);assert.equal(await f.quantity(HELI),0);
    assert.deepEqual(await f.q('SELECT * FROM inventory_logs'),[]);
    assert.deepEqual(await f.q('SELECT * FROM prime_draw_open_receipts_v1985'),[]);
  });

  for(const event of ['INSERT','UPDATE'])test(`${dialect}: a zero-row chip ${event} rolls back box debit, reward logs and receipt`,async t=>{
    const f=await fixture(t,dialect);
    await f.save({[ROCKET]:100});
    if(event==='UPDATE')await f.exec(`INSERT INTO cnine_user_inventory(user_id,item_code,quantity,unseen_quantity) VALUES(7,'${ROCKET}',5,2)`);
    const before=await f.q('SELECT * FROM cnine_user_inventory ORDER BY item_code');
    if(f.pg)await f.exec(`CREATE FUNCTION suppress_chip() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.item_code='${ROCKET}' THEN RETURN NULL; END IF; RETURN NEW; END $$;
      CREATE TRIGGER suppress_chip BEFORE ${event} ON cnine_user_inventory FOR EACH ROW EXECUTE FUNCTION suppress_chip();`);
    else await f.exec(`CREATE TRIGGER suppress_chip BEFORE ${event} ON cnine_user_inventory WHEN NEW.item_code='${ROCKET}' BEGIN SELECT RAISE(IGNORE); END;`);
    await assert.rejects(()=>f.open('suppressed-chip',2),/not.null|null value/i);
    assert.deepEqual(await f.q('SELECT * FROM cnine_user_inventory ORDER BY item_code'),before);
    assert.deepEqual(await f.q('SELECT * FROM inventory_logs'),[]);
    assert.deepEqual(await f.q('SELECT * FROM prime_draw_open_receipts_v1985'),[]);
    await f.exec(f.pg?'DROP TRIGGER suppress_chip ON cnine_user_inventory':'DROP TRIGGER suppress_chip');
    assert.equal((await f.open('suppressed-chip',2)).status,200);
    assert.equal(await f.quantity(ROCKET),event==='UPDATE'?7:2);
    assert.equal(await f.quantity(BOX),10);
  });
}
