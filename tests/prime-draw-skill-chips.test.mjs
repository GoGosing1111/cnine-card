class SqliteD1 {
  constructor(){this.db=new DatabaseSync(':memory:');}
  prepare(sql){
    const owner=this;
    return {values:[],bind(...values){this.values=values;return this},async first(){return owner.db.prepare(sql).get(...this.values)||null},async all(){return {results:owner.db.prepare(sql).all(...this.values)}},
      async run(){const result=owner.db.prepare(sql).run(...this.values);return {meta:{changes:Number(result.changes)},results:[]}}};
  }
  async batch(statements){this.db.exec('BEGIN');try{const results=[];for(const s of statements)results.push(await s.run());this.db.exec('COMMIT');return results}catch(error){this.db.exec('ROLLBACK');throw error}}
}
