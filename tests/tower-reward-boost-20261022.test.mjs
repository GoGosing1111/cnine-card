 assert.deepEqual((await pg.query('SELECT current_floor,highest_floor FROM tower_user_progress')).rows,[{current_floor:101,highest_floor:100}]);
 assert.equal((await pg.query('SELECT coin FROM users')).rows[0].coin,12345);
