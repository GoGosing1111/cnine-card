 let fail=false;const db={query:async(sql,values)=>{if(fail&&sql.startsWith('INSERT INTO app_meta'))throw Error('INJECTED_RECEIPT_FAILURE');const r=await pg.query(sql,values);return {...r,rowCount:r.affectedRows};}};
