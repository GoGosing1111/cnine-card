 assert.equal(at(60).coin,45000000000);assert.equal(at(61).coin,18750000000);
 assert.equal(at(100).coin,2000000000000);assert.equal(at(101).coin,50000000000);assert.equal(at(120).coin,800000000000);
 assert.equal(plan.filter(r=>r.multiplier!==1).length,99);
 assert.ok(plan.filter(r=>r.floor>100||r.floor===60).every(r=>r.coin===r.beforeCoin));
