 assert.equal((await inspectTowerAbyss(db)).beforeHash,snapshot.beforeHash);
 assert.equal((await pg.query('SELECT COUNT(*) AS n FROM admin_logs')).rows[0].n,0);
 const result=await applyRewardBoost(db,proof);assert.equal(result.receipt.changedFloors,99);
