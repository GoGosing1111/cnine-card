test('Tower operating route: the new 2-trillion reward is frozen at start and paid exactly once',async t=>{
 const f=await jointFixture(t,{postgres:true});
 const reward=2000000000000,tower=await operatingTowerFixture(f,{floorNo:100,maxFloor:120,rewardCoin:reward});
 const call=(path,body)=>tower.handle(path,new Request('https://game.example/api/'+path,{method:'POST',headers:{authorization:'Bearer local-account-7',origin:'https://game.example','content-type':'application/json'},body:JSON.stringify(body)}));
 const body={requestId:'tower-reward-boost-20261022-01',floorNo:100,protocol:TOWER_ABYSS_PROTOCOL},before=await f.coin();
 const response=await call('tower/start',body);assert.equal(response.status,200);
 const started=await response.json();assert.equal(started.result,'WIN');assert.equal(started.reward,0);
 assert.equal(await f.coin(),before);
 await f.p('UPDATE tower_floor_ranges SET reward_coin=1').run();
 f.setClock(started.settlement.notBefore);
 const finish=await call('tower/finish',{requestId:body.requestId});assert.equal(finish.status,200);
 assert.equal((await finish.json()).reward,reward);assert.equal(await f.coin(),before+reward);
 assert.equal((await call('tower/finish',{requestId:body.requestId})).status,200);
 assert.equal(await f.coin(),before+reward);
 assert.equal(Number((await f.p('SELECT COUNT(*) AS n FROM coin_logs WHERE user_id=7').first()).n),1);
 assert.equal(Number((await f.p('SELECT current_floor FROM tower_user_progress WHERE user_id=7').first()).current_floor),101);
});
