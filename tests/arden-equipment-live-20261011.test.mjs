import test from 'node:test';
import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {PGlite} from '@electric-sql/pglite';
import {ARDEN_ITEMS,OPERATION_KEY,registerArdenEquipment,verifyArdenEquipment} from '../scripts/ops/arden-equipment-live-20261011.mjs';

const assets=ARDEN_ITEMS.map(item=>({url:'https://cnine-card.pages.dev'+item.image,status:200,sha256:item.sha256}));
async function setup() {
  const db=new PGlite();
  await db.exec("CREATE TABLE character_equipment_items(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,code TEXT NOT NULL UNIQUE,name TEXT NOT NULL,slot TEXT NOT NULL,subtype TEXT NOT NULL DEFAULT '',rarity TEXT NOT NULL DEFAULT 'NORMAL',image_url TEXT NOT NULL DEFAULT '',description TEXT NOT NULL DEFAULT '',total_power BIGINT NOT NULL DEFAULT 0,pve_power BIGINT NOT NULL DEFAULT 0,pvp_power BIGINT NOT NULL DEFAULT 0,is_active BIGINT NOT NULL DEFAULT 1,is_public BIGINT NOT NULL DEFAULT 1,sort_order BIGINT NOT NULL DEFAULT 0,supply_enabled BIGINT NOT NULL DEFAULT 1,supply_weight DOUBLE PRECISION NOT NULL DEFAULT 1); CREATE TABLE app_meta(key TEXT PRIMARY KEY,value TEXT NOT NULL,updated_at TEXT); CREATE TABLE users(id BIGINT PRIMARY KEY,role TEXT,status TEXT); CREATE TABLE admin_logs(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,admin_id BIGINT,action_type TEXT,target_type TEXT,target_id TEXT,before_data TEXT,after_data TEXT,created_at TEXT); INSERT INTO users VALUES(1,'OWNER','ACTIVE'); INSERT INTO character_equipment_items(code,name,slot,subtype,rarity,total_power,pve_power,pvp_power,supply_enabled,supply_weight) VALUES('EMPEROR_TOP','엠퍼러 슈트','TOP','TOP','MYTHIC',100000,90000,10000,0,0);");
  await db.query('INSERT INTO app_meta(key,value) VALUES($1,$2)',['black_miracle_policy','{"equipment":[],"enabled":false}']);
  return db;
}

test('all four live image references match locked V5 approval bytes',async()=>{
  const approval=JSON.parse(await readFile(new URL('../preview/mythic-emperor-successor-v1/approval-20261008.json',import.meta.url),'utf8'));
  for(const item of ARDEN_ITEMS) {
    const bytes=await readFile(new URL('..'+item.image,import.meta.url));
    assert.equal(createHash('sha256').update(bytes).digest('hex'),item.sha256);
    assert.equal(approval.items.find(row=>row.key===item.key).sha256,item.sha256);
  }
});

test('catalog registration is public, grants are eligible, existing equipment and pool policy remain unchanged',async()=>{
  const db=await setup();try {
    const before=(await db.query("SELECT * FROM character_equipment_items WHERE code='EMPEROR_TOP'")).rows;
    const policy=(await db.query("SELECT * FROM app_meta WHERE key='black_miracle_policy'")).rows;
    await registerArdenEquipment(db,assets);
    const result=await verifyArdenEquipment(db);
    assert.equal(result.cmsVisible,true);assert.equal(result.publicAndActive,true);
    assert.equal(result.items.length,4);
    for(const item of result.items) {
      assert.equal(Number(item.total_power),200000);
      assert.equal(Number(item.pve_power),180000);assert.equal(Number(item.pvp_power),20000);
      assert.equal(item.rarity,'MYTHIC');
      assert.equal(Number(item.supply_enabled),0);assert.equal(Number(item.supply_weight),0);
    }
    assert.deepEqual((await db.query("SELECT * FROM character_equipment_items WHERE code='EMPEROR_TOP'")).rows,before);
    assert.deepEqual((await db.query("SELECT * FROM app_meta WHERE key='black_miracle_policy'")).rows,policy);
    assert.equal((await db.query("SELECT id FROM character_equipment_items WHERE code LIKE 'ARDEN_%' AND is_active=1")).rows.length,4);
  }finally{await db.close();}
});

test('retry preserves later CMS edits and does not duplicate catalog rows or audits',async()=>{
  const db=await setup();try {
    await registerArdenEquipment(db,assets);
    await db.query("UPDATE character_equipment_items SET total_power=300000,pve_power=270000,pvp_power=30000,description='owner edit',is_public=0 WHERE code='ARDEN_TOP'");
    const repeated=await registerArdenEquipment(db,assets);
    assert.equal(repeated.alreadyRegistered,true);
    const top=repeated.items.find(item=>item.code==='ARDEN_TOP');
    assert.equal(Number(top.total_power),300000);assert.equal(Number(top.is_public),0);
    assert.equal(top.description,'owner edit');
    assert.equal((await db.query('SELECT id FROM admin_logs')).rows.length,4);
    assert.equal((await db.query('SELECT id FROM character_equipment_items')).rows.length,5);
  }finally{await db.close();}
});

test('wrong live asset hash or duplicate identity blocks the whole operation',async()=>{
  const db=await setup();try {
    await assert.rejects(registerArdenEquipment(db,assets.map((row,i)=>i===0?{...row,sha256:'wrong'}:row)),/image hash mismatch/);
    assert.equal((await db.query('SELECT id FROM character_equipment_items')).rows.length,1);
    await db.query("INSERT INTO character_equipment_items(code,name,slot) VALUES('CUSTOM','아르덴 아머','TOP')");
    await assert.rejects(registerArdenEquipment(db,assets),/Matching Arden/);
    assert.equal((await db.query('SELECT id FROM admin_logs')).rows.length,0);
    assert.equal((await db.query('SELECT key FROM app_meta WHERE key=$1',[OPERATION_KEY])).rows.length,0);
  }finally{await db.close();}
});

test('partial insert and receipt failure roll back the entire catalog release',async()=>{
  const db=await setup();try {
    await db.exec("ALTER TABLE character_equipment_items ADD CONSTRAINT stop_third CHECK(code<>'ARDEN_SHOES')");
    await assert.rejects(registerArdenEquipment(db,assets));
    assert.equal((await db.query('SELECT id FROM character_equipment_items')).rows.length,1);
    await db.exec("ALTER TABLE character_equipment_items DROP CONSTRAINT stop_third; ALTER TABLE app_meta ADD CONSTRAINT stop_receipt CHECK(key NOT LIKE 'ops:arden-%')");
    await assert.rejects(registerArdenEquipment(db,assets));
    assert.equal((await db.query('SELECT id FROM character_equipment_items')).rows.length,1);
    assert.equal((await db.query('SELECT id FROM admin_logs')).rows.length,0);
    await db.exec('ALTER TABLE app_meta DROP CONSTRAINT stop_receipt');
    await registerArdenEquipment(db,assets);
    assert.equal((await db.query('SELECT key FROM app_meta WHERE key=$1',[OPERATION_KEY])).rows.length,1);
  }finally{await db.close();}
});
