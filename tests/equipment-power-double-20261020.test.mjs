import test from 'node:test';
import assert from 'node:assert/strict';
import {PGlite} from '@electric-sql/pglite';
import {TARGETS,OPERATION_KEY,applyEquipmentPowerIncrease,verifyEquipmentPowerIncrease} from '../scripts/ops/equipment-power-double-20261020.mjs';
import {forgePower} from '../shared/equipment-forge-policy-v1.mjs';
import {forgeEquipmentBonus} from '../functions/_equipment_forge_transactions.js';
import {__postgresCompatTest} from '../functions/_postgres_d1_compat.js';

async function fixture(){
  const db=new PGlite();
  await db.exec(`
    CREATE TABLE character_equipment_items(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,code TEXT UNIQUE,name TEXT,slot TEXT,total_power BIGINT,pve_power BIGINT,pvp_power BIGINT,is_active INTEGER DEFAULT 1,is_public INTEGER DEFAULT 1,image_url TEXT DEFAULT '/unchanged.webp',description TEXT DEFAULT 'keep',supply_enabled INTEGER DEFAULT 0,supply_weight DOUBLE PRECISION DEFAULT 0,updated_at TEXT DEFAULT 'before');
    CREATE TABLE users(id BIGINT PRIMARY KEY,nickname TEXT,role TEXT,status TEXT);
    CREATE TABLE app_meta(key TEXT PRIMARY KEY,value TEXT,updated_at TEXT);
    CREATE TABLE admin_logs(id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,admin_id BIGINT,action_type TEXT,target_type TEXT,target_id TEXT,before_data TEXT,after_data TEXT,created_at TEXT);
    CREATE TABLE user_equipment_instances(id BIGINT PRIMARY KEY,user_id BIGINT,equipment_id BIGINT);
    CREATE TABLE user_equipment_loadout(user_id BIGINT,slot TEXT,instance_id BIGINT);
    CREATE TABLE equipment_forge_states_v1(instance_id BIGINT,user_id BIGINT,level INTEGER,revision INTEGER);
    INSERT INTO users VALUES(1,'핑크빛유두','OWNER','ACTIVE');
    INSERT INTO app_meta VALUES('equipment_forge_runtime_policy_v1','{"mode":"ON","revision":6}','keep');
    INSERT INTO character_equipment_items(code,name,slot,total_power,pve_power,pvp_power) VALUES('SOVEREIGN','소버린 SKS','WEAPON',115000,103500,11500),('EASTERN_WEAPON_DRAFT_04','비공개 무기','WEAPON',0,0,0);
  `);
  for(const [i,row] of TARGETS.entries()){
    const {rows:[item]}=await db.query('INSERT INTO character_equipment_items(code,name,slot,total_power,pve_power,pvp_power) VALUES($1,$2,$3,$4,$5,$6) RETURNING id',[row.code,row.name,row.slot,row.beforeTotal,row.beforeTotal*.9,row.beforeTotal*.1]);
    await db.query('INSERT INTO user_equipment_instances VALUES($1,$2,$3)',[i+100,i+2,item.id]);
    await db.query('INSERT INTO user_equipment_loadout VALUES($1,$2,$3)',[i+2,row.slot,i+100]);
    await db.query('INSERT INTO equipment_forge_states_v1 VALUES($1,$2,10,2)',[i+100,i+2]);
  }
  return db;
}
const all=async(db,table)=>(await db.query('SELECT * FROM '+table+' ORDER BY 1')).rows;
const tables=['character_equipment_items','users','app_meta','admin_logs','user_equipment_instances','user_equipment_loadout','equipment_forge_states_v1'];
const snapshot=async db=>Object.fromEntries(await Promise.all(tables.map(async name=>[name,await all(db,name)])));

test('17 live catalog entries double from the already increased values; owned +10 equipment uses the new base, all other data is preserved',async()=>{
  const db=await fixture();
  try{
    const before=await snapshot(db);
    await applyEquipmentPowerIncrease(db);
    const result=await verifyEquipmentPowerIncrease(db);
    assert.equal(result.items.length,17);assert.equal(result.adminLogIds.length,17);
    const adapter=new __postgresCompatTest.PostgresD1Database({query:async(input,values)=>{
      const result=await db.query(typeof input==='string'?input:input.text,typeof input==='string'?values:input.values);
      return {...result,rowCount:result.affectedRows??result.rows.length};
    }});
    for(const [i,target] of TARGETS.entries()){
      const base=result.items.find(row=>row.code===target.code);
      assert.equal(base.totalPower,target.beforeTotal*2);
      for(let level=0;level<=10;level++){
        const old=forgePower(target.beforeTotal,level),next=forgePower(base.totalPower,level);
        assert.equal(next.total,old.total*2);
        assert.equal(next.pve+next.pvp,next.total);
      }
      const bonus=await forgeEquipmentBonus({DB:adapter},i+2),enhanced=forgePower(base.totalPower,10);
      assert.equal(base.pvePower+bonus.pve,enhanced.pve);
      assert.equal(base.pvpPower+bonus.pvp,enhanced.pvp);
    }
    const after=await snapshot(db);
    for(const name of ['users','user_equipment_instances','user_equipment_loadout','equipment_forge_states_v1'])assert.deepEqual(after[name],before[name]);
    assert.deepEqual(after.character_equipment_items.slice(0,2),before.character_equipment_items.slice(0,2));
    assert.deepEqual(after.app_meta.filter(row=>row.key!==OPERATION_KEY),before.app_meta);
  }finally{await db.close();}
});

test('retry is a no-op and preserves a later CMS adjustment',async()=>{
  const db=await fixture();
  try{
    await applyEquipmentPowerIncrease(db);
    await db.query("UPDATE character_equipment_items SET total_power=400000,pve_power=360000,pvp_power=40000 WHERE code='ARDEN_TOP'");
    const before=await snapshot(db),retry=await applyEquipmentPowerIncrease(db);
    assert.equal(retry.alreadyApplied,true);
    assert.deepEqual(await snapshot(db),before);
  }finally{await db.close();}
});

test('dry run and unexpected live power leave all rows unchanged',async()=>{
  const db=await fixture();
  try{
    const before=await snapshot(db);
    const dry=await applyEquipmentPowerIncrease(db,{dryRun:true});
    assert.equal(dry.dryRun,true);assert.deepEqual(await snapshot(db),before);
    await db.query("UPDATE character_equipment_items SET total_power=333333 WHERE code='ARDEN_TOP'");
    const changed=await snapshot(db);
    await assert.rejects(applyEquipmentPowerIncrease(db),/Live power changed/);
    assert.deepEqual(await snapshot(db),changed);
  }finally{await db.close();}
});

test('a late audit or receipt failure rolls back all power updates and audits',async()=>{
  const db=await fixture();
  try{
    const before=await snapshot(db);
    await db.exec("ALTER TABLE admin_logs ADD CONSTRAINT audit_failure CHECK(after_data NOT LIKE '%EASTERN_WEAPON_DRAFT_03%')");
    await assert.rejects(applyEquipmentPowerIncrease(db));
    assert.deepEqual(await snapshot(db),before);
    await db.exec("ALTER TABLE admin_logs DROP CONSTRAINT audit_failure; ALTER TABLE app_meta ADD CONSTRAINT receipt_failure CHECK(key NOT LIKE 'ops:equipment-power:%')");
    await assert.rejects(applyEquipmentPowerIncrease(db));
    assert.deepEqual(await snapshot(db),before);
  }finally{await db.close();}
});
